//! Orphan-page detection over in-memory pages.

// frob:ticket 01M67VEKBESFK2C23JMXV82RW9

use frob_doc::{Page, orphans};

fn scan(files: &[(&str, &str)]) -> Vec<String> {
    let pages: Vec<Page<'_>> = files
        .iter()
        .map(|(path, text)| Page { path, text })
        .collect();
    orphans(&pages).expect("pages parse")
}

// frob:tests orphans
#[test]
fn unlinked_page_is_an_orphan() {
    let found = scan(&[
        ("docs/README.md", "# Index\n\n[a](a.md)\n"),
        ("docs/a.md", "# A\n"),
        ("docs/lost.md", "# Lost\n"),
    ]);
    assert_eq!(found, ["docs/lost.md"]);
}

// frob:tests orphans
#[test]
fn reached_through_a_chain_and_a_root_page_is_not_orphan() {
    let found = scan(&[
        ("README.md", "# Top\n\n[guide](docs/guide/)\n"),
        (
            "docs/guide/README.md",
            "# Guide\n\n[more](deep/more.md#x)\n",
        ),
        ("docs/guide/deep/more.md", "# More\n\n[up](../../a.md)\n"),
        ("docs/a.md", "# A\n"),
    ]);
    assert!(found.is_empty(), "{found:?}");
}

// frob:tests orphans
#[test]
fn a_cycle_that_no_root_reaches_is_orphaned() {
    let found = scan(&[
        ("docs/README.md", "# Index\n"),
        ("docs/x.md", "# X\n\n[y](y.md)\n"),
        ("docs/y.md", "# Y\n\n[x](x.md)\n"),
    ]);
    assert_eq!(found, ["docs/x.md", "docs/y.md"]);
}

// frob:tests orphans
#[test]
fn generated_superseded_and_historical_pages_are_exempt() {
    let found = scan(&[
        ("docs/README.md", "# Index\n"),
        (
            "docs/gen.md",
            "<!-- GENERATED by frob v1: DO NOT EDIT. -->\n# G\n",
        ),
        ("docs/old.md", "# Old\n\nStatus: superseded-by new.md\n"),
        ("docs/past.md", "# Past\n\nStatus: historical\n"),
    ]);
    assert!(found.is_empty(), "{found:?}");
}

// frob:tests orphans
#[test]
fn links_in_code_and_external_links_do_not_count() {
    let found = scan(&[
        (
            "docs/README.md",
            "# Index\n\n`[a](a.md)`\n\n[web](https://example.com/b.md)\n",
        ),
        ("docs/a.md", "# A\n"),
    ]);
    assert_eq!(found, ["docs/a.md"]);
}
