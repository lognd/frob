//! The bounded `node_modules` walk-up.

// frob:ticket 01M7X35W2WATD06TP58JC8MS7H
use gob_fs::node_modules_dirs;

// frob:tests crates/gob-fs/src/node_modules.rs::node_modules_dirs
#[test]
fn nearest_first_and_never_above_the_root() {
    let dir = tempfile::tempdir().unwrap();
    let root = dir.path().join("repo");
    let cwd = root.join("pkg/app");
    std::fs::create_dir_all(cwd.join("node_modules")).unwrap();
    std::fs::create_dir_all(root.join("node_modules")).unwrap();
    std::fs::create_dir_all(dir.path().join("node_modules")).unwrap();
    assert_eq!(
        node_modules_dirs(&root, &cwd),
        [cwd.join("node_modules"), root.join("node_modules")]
    );
}

// frob:tests crates/gob-fs/src/node_modules.rs::node_modules_dirs
#[test]
fn a_node_modules_only_above_the_root_is_not_found() {
    let dir = tempfile::tempdir().unwrap();
    let root = dir.path().join("repo");
    let cwd = root.join("pkg");
    std::fs::create_dir_all(&cwd).unwrap();
    std::fs::create_dir_all(dir.path().join("node_modules")).unwrap();
    assert!(node_modules_dirs(&root, &cwd).is_empty());
    let elsewhere = dir.path().join("other");
    std::fs::create_dir_all(&elsewhere).unwrap();
    assert!(node_modules_dirs(&root, &elsewhere).is_empty());
}
