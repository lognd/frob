//! The bounded `node_modules` walk-up shared by every JavaScript tool lookup.
// frob:ticket 01M7X35W2WATD06TP58JC8MS7H

use std::path::{Path, PathBuf};

/// Every existing `node_modules` directory from `cwd` up to and including `root`, nearest first.
///
/// The walk never leaves `root`: a `node_modules` in a parent of the repository or project is not
/// the project's own install and is never returned. When `cwd` is not at or below `root` only
/// `cwd`'s own `node_modules` is considered, so a stray `cwd` cannot walk to the filesystem root.
pub fn node_modules_dirs(root: &Path, cwd: &Path) -> Vec<PathBuf> {
    let mut found = Vec::new();
    let inside = cwd.starts_with(root);
    for dir in cwd.ancestors() {
        let candidate = dir.join("node_modules");
        if candidate.is_dir() {
            found.push(candidate);
        }
        if !inside || dir == root {
            break;
        }
    }
    found
}
