//! The secret-free nudge workflow generated onto the ticket branch (mirror.md 3.1, 5).
// frob:ticket 01M4052VF61FCR6FQS2KSS1NJG
//!
//! The one `.github/` file allowed on the ticket branch. It sends a
//! `repository_dispatch` meaning only "something changed"; it references no
//! secrets and no environment, and skips pushes made by a mirror bot id. The
//! bytes are a pure function of the [`NudgeSpec`], so rule `TICK008` can
//! byte-compare the committed file against [`render`].

use std::fmt;

/// Repository-relative path of the generated nudge workflow.
pub const NUDGE_PATH: &str = ".github/workflows/frob-mirror-nudge.yml";

/// The `repository_dispatch` event type the nudge sends.
pub const NUDGE_EVENT_TYPE: &str = "frob-ledger-changed";

/// Inputs that determine the nudge workflow bytes.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct NudgeSpec {
    /// The ticket branch whose pushes trigger the nudge.
    pub ticket_branch: String,
    /// GitHub user ids of the mirror's own App identities (`[mirror] bot_ids`).
    pub bot_ids: Vec<u64>,
}

/// Why a [`NudgeSpec`] cannot be rendered.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum NudgeError {
    /// The branch name is empty or has characters unsafe to embed in YAML.
    BadBranch(String),
}

impl fmt::Display for NudgeError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::BadBranch(b) => write!(f, "ticket branch {b:?} is not a plain ref name"),
        }
    }
}

impl std::error::Error for NudgeError {}

/// True when `branch` is non-empty and only ASCII alphanumerics or `._/-`.
fn branch_is_plain(branch: &str) -> bool {
    !branch.is_empty()
        && branch
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || matches!(c, '.' | '_' | '/' | '-'))
}

/// Render the nudge workflow for `spec`; the same spec always yields the same bytes.
///
/// # Errors
///
/// [`NudgeError::BadBranch`] when the branch name is not a plain ref name.
pub fn render(spec: &NudgeSpec) -> Result<String, NudgeError> {
    if !branch_is_plain(&spec.ticket_branch) {
        tracing::warn!(branch = %spec.ticket_branch, "nudge workflow refused: unsafe branch name");
        return Err(NudgeError::BadBranch(spec.ticket_branch.clone()));
    }
    let mut ids = spec.bot_ids.clone();
    ids.sort_unstable();
    ids.dedup();
    let list = ids
        .iter()
        .map(|id| format!("\"{id}\""))
        .collect::<Vec<_>>()
        .join(", ");
    let branch = &spec.ticket_branch;
    let event = NUDGE_EVENT_TYPE;
    tracing::debug!(branch = %branch, bot_ids = ids.len(), "rendering nudge workflow");
    Ok(format!(
        "# Generated by frob; do not edit (rule TICK008 byte-compares this file).\n\
         # Sends a bare repository_dispatch: nothing the mirror trusts travels in it.\n\
         name: frob-mirror-nudge\n\
         on:\n\
         \x20 push:\n\
         \x20   branches:\n\
         \x20     - '{branch}'\n\
         permissions:\n\
         \x20 contents: write\n\
         jobs:\n\
         \x20 nudge:\n\
         \x20   runs-on: ubuntu-latest\n\
         \x20   if: ${{{{ !contains(fromJSON('[{list}]'), github.actor_id) }}}}\n\
         \x20   steps:\n\
         \x20     - name: Send repository_dispatch\n\
         \x20       run: |\n\
         \x20         curl --fail --silent --show-error -X POST \\\n\
         \x20           -H 'Accept: application/vnd.github+json' \\\n\
         \x20           -H \"Authorization: Bearer ${{{{ github.token }}}}\" \\\n\
         \x20           \"${{{{ github.api_url }}}}/repos/${{{{ github.repository }}}}/dispatches\" \\\n\
         \x20           -d '{{\"event_type\": \"{event}\"}}'\n"
    ))
}

#[cfg(test)]
mod tests {
    use super::*;

    fn spec() -> NudgeSpec {
        NudgeSpec { ticket_branch: "frob/tickets".into(), bot_ids: vec![42, 7, 42] }
    }

    // frob:tests render
    #[test]
    fn render_twice_is_byte_identical() {
        assert_eq!(render(&spec()).unwrap(), render(&spec()).unwrap());
        let mut shuffled = spec();
        shuffled.bot_ids = vec![7, 42];
        assert_eq!(render(&spec()).unwrap(), render(&shuffled).unwrap());
    }

    // frob:tests render
    #[test]
    fn render_references_no_secrets_or_environment() {
        let text = render(&spec()).unwrap().to_lowercase();
        assert!(!text.contains("secrets"));
        assert!(!text.contains("environment"));
        assert!(!text.contains("\nenv:") && !text.contains(" env:"));
        assert!(text.is_ascii());
    }

    // frob:tests render
    #[test]
    fn render_skips_mirror_bot_pushes() {
        let text = render(&spec()).unwrap();
        assert!(text.contains("contains(fromJSON('[\"7\", \"42\"]'), github.actor_id)"));
        assert!(text.contains("- 'frob/tickets'"));
        assert!(text.contains(NUDGE_EVENT_TYPE));
    }

    // frob:tests render
    #[test]
    fn render_rejects_unsafe_branch() {
        let bad = NudgeSpec { ticket_branch: "a'b".into(), bot_ids: vec![] };
        assert!(matches!(render(&bad), Err(NudgeError::BadBranch(_))));
    }
}
