//! `guide/**` and `.gitattributes`: pages installed from templates shipped in the binary
//! (`navigation.md` sections 3.1 and 4.1).
//!
//! The templates live in `templates/` and are compiled in. Placeholders (`{{frob}}`,
//! `{{version}}`, `{{handle_min_len}}`) are filled from the repository's settings. The only
//! version-dependent text outside the template bodies is the marker line, so a newer frob
//! changes a file by its template text and that one line.
// frob:ticket 01M3ZX86G8HFRDA78PBVFSTJNW

use crate::reindex::{GENERATED_MARKER_PREFIX, GenInput};

/// One installed file: where it goes and its template text.
#[derive(Debug, Clone, Copy)]
pub struct Template {
    /// Branch-relative output path.
    pub path: &'static str,
    /// Template text with `{{name}}` placeholders.
    pub body: &'static str,
}

/// The files installed by the binary, in path order.
pub const TEMPLATES: &[Template] = &[
    Template {
        path: ".gitattributes",
        body: include_str!("../../templates/gitattributes"),
    },
    Template {
        path: "guide/README.md",
        body: include_str!("../../templates/guide/README.md"),
    },
    Template {
        path: "guide/new/first-ticket.md",
        body: include_str!("../../templates/guide/new/first-ticket.md"),
    },
    Template {
        path: "guide/new/reading-a-ticket.md",
        body: include_str!("../../templates/guide/new/reading-a-ticket.md"),
    },
    Template {
        path: "guide/work/how-to.md",
        body: include_str!("../../templates/guide/work/how-to.md"),
    },
    Template {
        path: "guide/work/why-a-branch.md",
        body: include_str!("../../templates/guide/work/why-a-branch.md"),
    },
];

/// The command name used in the rendered guide.
const COMMAND: &str = "frob";

/// Fill the `{{name}}` placeholders of `body`.
fn fill(body: &str, version: &str, handle_min_len: usize) -> String {
    body.replace("{{frob}}", COMMAND)
        .replace("{{version}}", version)
        .replace("{{handle_min_len}}", &handle_min_len.to_string())
}

/// The first line of an installed file: a marker comment in the file's own syntax.
fn marker(path: &str, version: &str) -> String {
    if path == ".gitattributes" {
        format!("# GENERATED by frob v{version}: DO NOT EDIT\n")
    } else {
        format!("{GENERATED_MARKER_PREFIX} v{version}: DO NOT EDIT -->\n")
    }
}

/// Render `templates` for `input`.
#[must_use]
pub fn render_with(input: &GenInput<'_>, templates: &[Template]) -> Vec<(String, Vec<u8>)> {
    templates
        .iter()
        .map(|t| {
            let text = format!(
                "{}{}",
                marker(t.path, input.version),
                fill(t.body, input.version, input.handle_min_len)
            );
            (t.path.to_owned(), text.into_bytes())
        })
        .collect()
}

/// Render every built-in template.
#[must_use]
pub fn render(input: &GenInput<'_>) -> Vec<(String, Vec<u8>)> {
    render_with(input, TEMPLATES)
}
