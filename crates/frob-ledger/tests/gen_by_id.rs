//! `indexes/by-id/<xx>.md`: one page lists each ticket with its current path (`navigation.md` section 1).
// frob:ticket 01M3ZX868H7TQ34ZDPXY13NRRG

use frob_ledger::r#gen::{GENERATORS, by_id};
use frob_ledger::model::{Category, Class, Frontmatter, Priority, Stamp, Ticket, TicketType};
use frob_ledger::reindex::{ReindexOptions, Tree, reindex};
use frob_ledger::{TicketId, doc};

fn ticket(ty: TicketType, title: &str, parent: Option<TicketId>) -> (TicketId, String) {
    let id = TicketId::mint();
    let front = Frontmatter {
        id,
        title: title.into(),
        ty,
        flavour: None,
        category: Category::Todo,
        outcome: None,
        priority: Priority::High,
        class: Class::Standard,
        due: None,
        points: None,
        parent,
        reporter: "t".into(),
        assignee: None,
        created: Stamp::from_unix(1_790_000_000),
        updated: Stamp::from_unix(1_790_000_000),
        persona: None,
        capability: None,
        outcome_text: None,
        idempotency_key: None,
        aliases: vec![],
        labels: vec![],
        scope: vec![],
        links: vec![],
        acceptance: vec![],
    };
    let text = doc::render(&Ticket {
        front,
        body: "body".into(),
    })
    .expect("render");
    (id, text)
}

fn run(tree: &Tree) -> Tree {
    let opts = ReindexOptions {
        version: "9.9.9",
        handle_min_len: 7,
        generators: GENERATORS,
    };
    reindex(tree, &opts).expect("reindex").tree
}

fn pages(tree: &Tree) -> Vec<(&String, String)> {
    tree.iter()
        .filter(|(p, _)| p.starts_with("indexes/by-id/"))
        .map(|(p, b)| (p, String::from_utf8(b.clone()).expect("utf8")))
        .collect()
}

#[test]
fn every_ticket_is_listed_on_exactly_one_page_with_its_current_path() {
    let (epic, epic_text) = ticket(TicketType::Epic, "Navigation", None);
    let mut tree = Tree::new();
    tree.insert("navigation/EPIC.md".into(), epic_text.into_bytes());
    let mut all = vec![epic];
    for i in 0..40 {
        let (id, text) = ticket(TicketType::Task, &format!("Task {i} | piped"), Some(epic));
        tree.insert(format!("navigation/old-{i}.md"), text.into_bytes());
        all.push(id);
    }
    let out = run(&tree);
    let pages = pages(&out);
    for id in &all {
        let hits: Vec<_> = pages
            .iter()
            .filter(|(_, t)| t.contains(&id.to_string()))
            .collect();
        assert_eq!(hits.len(), 1, "{id}");
        assert_eq!(hits[0].0, &by_id::page_path(*id));
        let row = hits[0]
            .1
            .lines()
            .find(|l| l.contains(&id.to_string()))
            .expect("row");
        let path = out
            .iter()
            .find(|(p, b)| {
                !p.starts_with("indexes/")
                    && std::str::from_utf8(b).is_ok_and(|t| {
                        t.contains(&format!("id: {id}")) || t.contains(&id.to_string())
                    })
            })
            .map(|(p, _)| p.clone())
            .expect("ticket file");
        assert!(
            row.contains(&format!("({}{path})", "../../")),
            "{row} vs {path}"
        );
    }
    assert!(
        pages
            .iter()
            .all(|(_, t)| t.starts_with("<!-- GENERATED by frob"))
    );
}

#[test]
fn a_moved_ticket_shows_its_new_path_after_regeneration() {
    let (epic_a, a_text) = ticket(TicketType::Epic, "Alpha", None);
    let (epic_b, b_text) = ticket(TicketType::Epic, "Beta", None);
    let (task, task_text) = ticket(TicketType::Task, "Move me", Some(epic_a));
    let mut tree = Tree::new();
    tree.insert("alpha/EPIC.md".into(), a_text.into_bytes());
    tree.insert("beta/EPIC.md".into(), b_text.into_bytes());
    tree.insert("alpha/move-me.md".into(), task_text.clone().into_bytes());
    let first = run(&tree);
    let page = by_id::page_path(task);
    let before = String::from_utf8(first[&page].clone()).expect("utf8");
    assert!(before.contains("(../../alpha/move-me.md)"), "{before}");

    // The ticket is reparented under Beta: the file content changes its parent.
    let moved = task_text.replace(&epic_a.to_string(), &epic_b.to_string());
    let mut tree = first.clone();
    tree.remove("alpha/move-me.md");
    tree.insert("alpha/move-me.md".into(), moved.into_bytes());
    let second = run(&tree);
    let after = String::from_utf8(second[&page].clone()).expect("utf8");
    assert!(after.contains("(../../beta/move-me.md)"), "{after}");
    assert!(!after.contains("alpha/move-me.md"), "{after}");
    assert_eq!(run(&second), second, "regeneration is stable");
}
