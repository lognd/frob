//! GX014 through `crunk check`: a uGUI prefab generator must use generated token constants.

// frob:ticket 01M4CXSD8DEYB69E5J7Q1ABGXK

use std::path::Path;

use crunk_check::{CheckOptions, run};

fn write(root: &Path, rel: &str, text: &str) {
    let path = root.join(rel);
    std::fs::create_dir_all(path.parent().expect("parent")).expect("mkdir");
    std::fs::write(path, text).expect("write");
}

/// GX014 findings of one C# file in a fresh repository holding the default preset.
fn gx014_of(source: &str) -> Vec<gob_rules::Finding> {
    let dir = tempfile::tempdir().expect("tempdir");
    write(
        dir.path(),
        "crunk.toml",
        crunk_spec::presets::preset("default").expect("default preset"),
    );
    write(dir.path(), "Editor/HudPrefabBuilder.cs", source);
    run(dir.path(), &CheckOptions::default())
        .expect("run")
        .report
        .findings
        .into_iter()
        .filter(|f| f.rule.as_str() == "GX014")
        .collect()
}

/// A generator body around `line`.
fn generator(line: &str) -> String {
    format!(
        "using UnityEditor;\nclass HudPrefabBuilder {{\n  void Build() {{\n    {line}\n    PrefabUtility.SaveAsPrefabAsset(go, \"Hud.prefab\");\n  }}\n}}\n"
    )
}

// frob:tests crates/crunk-check/src/ugui.rs::Gx014
#[test]
fn a_color_literal_asks_for_the_generated_token_constant() {
    let f = gx014_of(&generator("img.color = new Color(0.1f, 0.2f, 0.3f, 1f);"));
    assert_eq!(f.len(), 1, "{f:?}");
    assert!(
        f[0].message.contains("generated token constant"),
        "{}",
        f[0].message
    );
    assert!(f[0].message.contains("new Color(0.1f"), "{}", f[0].message);
}

// frob:tests crates/crunk-check/src/ugui.rs::UguiLiteralCheck
#[test]
fn named_colors_hex_strings_and_font_sizes_are_literals() {
    assert_eq!(gx014_of(&generator("img.color = Color.white;")).len(), 1);
    assert_eq!(
        gx014_of(&generator(
            "ColorUtility.TryParseHtmlString(\"#112233\", out var c);"
        ))
        .len(),
        1
    );
    assert_eq!(gx014_of(&generator("label.fontSize = 18;")).len(), 1);
}

// frob:tests crates/crunk-check/src/ugui.rs::UguiLiteralCheck
#[test]
fn token_constants_comments_and_strings_are_clean() {
    assert!(gx014_of(&generator("img.color = HudTokens.ColorInk;")).is_empty());
    assert!(gx014_of(&generator("label.fontSize = HudTokens.TypeBody;")).is_empty());
    assert!(
        gx014_of(&generator(
            "// was new Color(1f, 0f, 0f)\n    Log(\"Color.white\");"
        ))
        .is_empty()
    );
    assert!(gx014_of(&generator("img.color = Color.clear;")).is_empty());
}

// frob:tests crates/crunk-check/src/ugui.rs::UguiLiteralCheck
#[test]
fn generated_token_files_and_non_generators_are_exempt() {
    let tokens = "// GENERATED by crunk tokens -- edit crunk.toml instead.\nusing UnityEditor;\nclass T { static Color Ink = new Color(0.1f, 0.1f, 0.1f); void F() { PrefabUtility.X(); } }\n";
    assert!(gx014_of(tokens).is_empty());
    let runtime = "class Flash { Color c = new Color(1f, 0f, 0f); }\n";
    assert!(gx014_of(runtime).is_empty());
}

// frob:tests crates/crunk-check/src/ugui.rs::UguiLiteralCheck
#[test]
fn a_waiver_with_a_reason_silences_it() {
    let src = generator("img.color = Color.red; // crunk:waive GX014 reason=\"debug tint\"");
    let f = gx014_of(&src);
    assert!(f.is_empty(), "{f:?}");
}
