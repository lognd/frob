//! GX014: a prefab generator (C# that writes uGUI prefabs) must take colours and font sizes from
//! the generated token constants (`crunk export csharp`), never from literals (crunk.md section 7).
//!
//! The check is a [`FileCheck`] over `.cs` files: only files that call `PrefabUtility.` are
//! generators, the generated token class itself (it carries the `GENERATED` banner) is exempt,
//! and comments and string contents are never scanned.
//!
//! The same check also audits `.prefab` files read-only ([`prefab_literals`]): a `Color` flow
//! mapping with numeric channels and a numeric font size are literals; a colour or size that is not
//! a plain number (an alias, a block mapping, a malformed or unterminated flow mapping) is
//! Unresolved, and so is a prefab that is not text YAML (a binary-serialized one). Nothing is ever
//! written back.
//!
//! A colour built from arguments that are not all numeric literals (`new Color(r, g, b)`,
//! `Color.Lerp(a, b, t)`) is Unresolved: the value may or may not come from a generated token, and
//! the check does not trace it. Plain assignments of a variable or field are not judged at all.

// frob:ticket 01M4CXSD8DEYB69E5J7Q1ABGXK
// frob:ticket 01M5HW48KRXEE8ARBE3N2JPRYH

use std::path::Path;

use gob_check::{CheckCtx, FileCheck, SharedCtx};
use gob_rules::{Finding, Rule, RuleMeta, Severity, UnresolvedReason};
use gob_text::{FileId, Span, TextRange, TextSize};

use crate::Crunk;

/// A uGUI prefab generator holds a colour or font-size literal instead of a generated token.
#[derive(Debug, Clone, Copy, Default, Rule)]
#[rule(
    id = "GX014",
    slug = "ugui-literal-not-token",
    family = "GX",
    product = "crunk",
    severity = Error,
    tier = Universal,
    scope = File,
    fix = Manual,
    version = 1
)]
pub struct Gx014;

/// Named `UnityEngine.Color` statics that are literals in disguise (`Color.clear` is not).
const NAMED_COLORS: [&str; 10] = [
    "white", "black", "red", "green", "blue", "yellow", "cyan", "magenta", "gray", "grey",
];

/// `UnityEngine.Color` static methods that compute a colour from arguments GX014 cannot trace.
const COMPUTED_COLORS: [&str; 3] = ["Lerp", "LerpUnclamped", "HSVToRGB"];

/// The Unresolved reason code of a computed colour.
const COMPUTED_COLOR_REASON: &str = "computed-color";

/// The Unresolved reason code of a prefab colour or font size that is not a plain number.
const PREFAB_VALUE_REASON: &str = "non-literal-prefab-value";

/// The Unresolved reason code of a prefab that is not text YAML.
const PREFAB_BINARY_REASON: &str = "binary-prefab";

/// Prefab YAML keys that hold a `Color` flow mapping.
const PREFAB_COLOR_KEYS: [&str; 4] = ["m_Color", "m_fontColor", "m_FontColor", "m_OutlineColor"];

/// Prefab YAML keys that hold a font size.
const PREFAB_SIZE_KEYS: [&str; 2] = ["m_FontSize", "m_fontSize"];

/// Names of the banners a generated token file carries (`CSHARP_BANNER` and the `<auto-generated` form).
const GENERATED_MARKERS: [&str; 2] = ["GENERATED", "<auto-generated"];

/// The [`FileCheck`] that emits [`Gx014`] over `.cs` prefab generators.
#[derive(Debug, Clone, Copy, Default)]
pub struct UguiLiteralCheck;

/// One literal found in a generator: byte range and what to tell the author.
#[derive(Debug, PartialEq, Eq)]
pub(crate) struct Hit {
    /// Byte offset of the literal.
    pub offset: usize,
    /// Byte length of the flagged text.
    pub len: usize,
    /// The finding message.
    pub message: String,
    /// True when the source cannot be judged (a computed colour): reported Unresolved, not as a literal.
    pub unresolved: bool,
    /// The Unresolved reason code (meaningful only when `unresolved`).
    pub reason: &'static str,
}

/// `text` with comments (and, when `strings`, string/char literal contents) blanked to spaces,
/// keeping every byte offset and newline.
fn mask(text: &str, strings: bool) -> String {
    let b = text.as_bytes();
    let mut out = b.to_vec();
    let blank = |out: &mut [u8], from: usize, to: usize| {
        for byte in &mut out[from..to] {
            if *byte != b'\n' {
                *byte = b' ';
            }
        }
    };
    let mut i = 0;
    while i < b.len() {
        match b[i] {
            b'/' if b.get(i + 1) == Some(&b'/') => {
                let end = text[i..].find('\n').map_or(b.len(), |n| i + n);
                blank(&mut out, i, end);
                i = end;
            }
            b'/' if b.get(i + 1) == Some(&b'*') => {
                let end = text[i + 2..].find("*/").map_or(b.len(), |n| i + 2 + n + 2);
                blank(&mut out, i, end);
                i = end;
            }
            q @ (b'"' | b'\'') => {
                let mut j = i + 1;
                while j < b.len() && b[j] != q && b[j] != b'\n' {
                    j += if b[j] == b'\\' { 2 } else { 1 };
                }
                let end = j.min(b.len());
                if strings {
                    blank(&mut out, i + 1, end);
                }
                i = (end + 1).min(b.len());
            }
            _ => i += 1,
        }
    }
    String::from_utf8(out).unwrap_or_default()
}

/// True when `c` can continue a C# identifier.
fn is_ident(c: u8) -> bool {
    c.is_ascii_alphanumeric() || c == b'_'
}

/// True when `args` is made only of numeric literals and arithmetic on them.
fn all_numeric(args: &str) -> bool {
    let b = args.as_bytes();
    !args.trim().is_empty()
        && b.iter().enumerate().all(|(i, &c)| match c {
            b'0'..=b'9' | b'.' | b',' | b'+' | b'-' | b'*' | b'/' | b'(' | b')' => true,
            c if c.is_ascii_whitespace() => true,
            b'f' | b'F' | b'd' | b'D' => i > 0 && (b[i - 1].is_ascii_digit() || b[i - 1] == b'.'),
            _ => false,
        })
}

/// `args` with each leading C# named-argument label (`r: 1f`) removed from its comma-separated pieces.
fn strip_labels(args: &str) -> String {
    args.split(',')
        .map(|piece| {
            let trimmed = piece.trim_start();
            let name_len = trimmed.bytes().take_while(|&c| is_ident(c)).count();
            let rest = trimmed[name_len..].trim_start();
            if name_len > 0 && rest.starts_with(':') {
                &rest[1..]
            } else {
                piece
            }
        })
        .collect::<Vec<_>>()
        .join(",")
}

/// The matching close paren of the `(` at `open` in `code`.
fn close_paren(code: &str, open: usize) -> Option<usize> {
    let mut depth = 0usize;
    for (i, c) in code.bytes().enumerate().skip(open) {
        match c {
            b'(' => depth += 1,
            b')' => {
                depth -= 1;
                if depth == 0 {
                    return Some(i);
                }
            }
            _ => {}
        }
    }
    None
}

/// Push a hit for every `new Color(...)` / `new Color32(...)`: a literal fires, computed arguments are Unresolved.
fn ctor_hits(text: &str, code: &str, hits: &mut Vec<Hit>) {
    for ctor in ["new Color(", "new Color32("] {
        for (at, _) in code.match_indices(ctor) {
            let open = at + ctor.len() - 1;
            let Some(close) = close_paren(code, open) else {
                continue;
            };
            let args = &code[open + 1..close];
            if args.trim().is_empty() {
                continue;
            }
            let shown = text[at..=close]
                .split_whitespace()
                .collect::<Vec<_>>()
                .join(" ");
            if all_numeric(&strip_labels(args)) {
                hits.push(Hit {
                    offset: at,
                    len: close + 1 - at,
                    message: format!(
                        "colour literal `{shown}` in a prefab generator; use the generated token constant (`crunk export csharp`) instead"
                    ),
                    unresolved: false,
                    reason: COMPUTED_COLOR_REASON,
                });
            } else {
                tracing::debug!(%shown, "GX014: computed colour argument, undecidable");
                hits.push(Hit {
                    offset: at,
                    len: close + 1 - at,
                    message: format!(
                        "colour `{shown}` is built from non-literal arguments; GX014 cannot tell whether they come from a generated token"
                    ),
                    unresolved: true,
                    reason: COMPUTED_COLOR_REASON,
                });
            }
        }
    }
}

/// Every colour and font-size literal of a prefab generator `text` (empty for other files).
pub(crate) fn literals(text: &str) -> Vec<Hit> {
    let head: String = text.lines().take(8).collect::<Vec<_>>().join("\n");
    if GENERATED_MARKERS.iter().any(|m| head.contains(m)) {
        tracing::debug!("GX014: generated token file, exempt");
        return Vec::new();
    }
    let code = mask(text, true);
    if !code.contains("PrefabUtility.") {
        return Vec::new();
    }
    let mut hits = Vec::new();
    ctor_hits(text, &code, &mut hits);
    for (at, _) in code.match_indices("Color.") {
        let before_ok =
            at == 0 || !(is_ident(code.as_bytes()[at - 1]) || code.as_bytes()[at - 1] == b'.');
        let rest = &code[at + 6..];
        let word: String = rest
            .chars()
            .take_while(char::is_ascii_alphanumeric)
            .collect();
        if before_ok && NAMED_COLORS.contains(&word.as_str()) {
            hits.push(Hit {
                offset: at,
                len: 6 + word.len(),
                message: format!(
                    "named colour `Color.{word}` in a prefab generator; use the generated token constant (`crunk export csharp`) instead"
                ),
                unresolved: false,
                    reason: COMPUTED_COLOR_REASON,
            });
        } else if before_ok && COMPUTED_COLORS.contains(&word.as_str()) {
            tracing::debug!(%word, "GX014: computed colour method, undecidable");
            hits.push(Hit {
                offset: at,
                len: 6 + word.len(),
                message: format!(
                    "`Color.{word}` computes a colour from its arguments; GX014 cannot tell whether they come from a generated token"
                ),
                unresolved: true,
                    reason: COMPUTED_COLOR_REASON,
            });
        }
    }
    let with_strings = mask(text, false);
    for (at, _) in with_strings.match_indices("TryParseHtmlString(") {
        let rest = with_strings[at + 19..].trim_start();
        if rest.starts_with("\"#") {
            hits.push(Hit {
                offset: at,
                len: 19,
                message: "hex colour literal in a prefab generator; use the generated token constant (`crunk export csharp`) instead".to_owned(),
                unresolved: false,
                    reason: COMPUTED_COLOR_REASON,
            });
        }
    }
    for (at, _) in code.match_indices("fontSize") {
        let b = code.as_bytes();
        if at > 0 && is_ident(b[at - 1]) {
            continue;
        }
        let rest = code[at + 8..].trim_start();
        let Some(rest) = rest.strip_prefix('=') else {
            continue;
        };
        if rest.starts_with('=') {
            continue;
        }
        let num: String = rest
            .trim_start()
            .chars()
            .take_while(|c| c.is_ascii_digit() || *c == '.')
            .collect();
        let after = rest.trim_start()[num.len()..].trim_start_matches(['f', 'F']);
        if !num.is_empty() && !after.starts_with(|c: char| is_ident(c as u8)) {
            hits.push(Hit {
                offset: at,
                len: 8,
                message: format!(
                    "font-size literal `{num}` in a prefab generator; use the generated token constant (`crunk export csharp`) instead"
                ),
                unresolved: false,
                    reason: COMPUTED_COLOR_REASON,
            });
        }
    }
    hits.sort_by_key(|h| h.offset);
    hits
}

/// True when `text` is a Unity text-serialized YAML document (binary-serialized prefabs are not).
fn is_text_yaml(text: &str) -> bool {
    text.trim_start_matches('\u{feff}').starts_with("%YAML")
}

/// True when `v` is a plain YAML number.
fn is_number(v: &str) -> bool {
    v.parse::<f64>().is_ok_and(f64::is_finite)
}

/// `value` without a trailing YAML comment (a `#` after whitespace) and surrounding blanks.
fn strip_comment(value: &str) -> &str {
    let cut = value
        .match_indices('#')
        .find(|(i, _)| *i == 0 || value[..*i].ends_with([' ', '\t']))
        .map_or(value.len(), |(i, _)| i);
    value[..cut].trim()
}

/// Whether the flow mapping `{r: 1, g: 0, b: 0, a: 1}` (braces included) is all numeric channels.
/// `None` when it is malformed (no closing brace, a pair without a colon, a missing r, g or b).
fn color_flow_is_literal(flow: &str) -> Option<bool> {
    let inner = flow.strip_prefix('{')?.strip_suffix('}')?;
    let (mut seen, mut literal) = (0u8, true);
    for pair in inner.split(',') {
        let (key, value) = pair.split_once(':')?;
        let value = value.trim();
        match key.trim() {
            "r" => seen |= 1,
            "g" => seen |= 2,
            "b" => seen |= 4,
            "a" => {}
            _ => return None,
        }
        literal &= is_number(value);
    }
    (seen == 7).then_some(literal)
}

/// Every colour and font-size literal of a Unity text prefab (read-only; the text is never changed).
///
/// A numeric `Color` flow mapping or font size is a literal. A colour that is an alias, a block
/// mapping, malformed, or has a non-numeric channel, and a font size that is not a number, are
/// Unresolved; so is a prefab whose text is not `%YAML` (binary serialization), reported once at
/// offset zero. Document markers (`--- !u!114 &1`), directives and comments are skipped.
pub(crate) fn prefab_literals(text: &str) -> Vec<Hit> {
    if !is_text_yaml(text) {
        tracing::debug!("GX014: prefab is not text YAML, undecidable");
        return vec![Hit {
            offset: 0,
            len: 0,
            message: "prefab is not text-serialized YAML (binary or unknown format); GX014 cannot audit its colours and font sizes".to_owned(),
            unresolved: true,
            reason: PREFAB_BINARY_REASON,
        }];
    }
    let mut hits = Vec::new();
    let mut offset = 0;
    for line in text.split_inclusive('\n') {
        let at = offset;
        offset += line.len();
        let body = line.trim_start().trim_start_matches("- ").trim_start();
        if body.starts_with(['#', '%']) || body.starts_with("---") {
            continue;
        }
        let Some((key, value)) = body.split_once(':') else {
            continue;
        };
        let key = key.trim();
        let value = strip_comment(value);
        let shown_len = line.trim_end().len();
        if PREFAB_COLOR_KEYS.contains(&key) {
            match color_flow_is_literal(value) {
                Some(true) => hits.push(Hit {
                    offset: at,
                    len: shown_len,
                    message: format!(
                        "colour literal `{key}: {value}` in a prefab; use the generated token constant (`crunk export csharp`) instead"
                    ),
                    unresolved: false,
                    reason: PREFAB_VALUE_REASON,
                }),
                Some(false) | None => hits.push(Hit {
                    offset: at,
                    len: shown_len,
                    message: format!(
                        "`{key}` in a prefab is not a plain numeric colour; GX014 cannot judge it"
                    ),
                    unresolved: true,
                    reason: PREFAB_VALUE_REASON,
                }),
            }
        } else if PREFAB_SIZE_KEYS.contains(&key) && !value.is_empty() {
            let literal = is_number(value);
            hits.push(Hit {
                offset: at,
                len: shown_len,
                message: if literal {
                    format!(
                        "font-size literal `{value}` in a prefab; use the generated token constant (`crunk export csharp`) instead"
                    )
                } else {
                    format!("`{key}` in a prefab is not a plain number; GX014 cannot judge it")
                },
                unresolved: !literal,
                reason: PREFAB_VALUE_REASON,
            });
        }
    }
    hits
}

/// True when `path` names a Unity prefab.
fn is_prefab(path: &str) -> bool {
    Path::new(path).extension().is_some_and(|e| e == "prefab")
}

impl FileCheck<Crunk> for UguiLiteralCheck {
    fn rules(&self) -> Vec<&'static RuleMeta> {
        vec![Gx014.meta()]
    }

    fn applies(&self, _ctx: &SharedCtx<'_, Crunk>, path: &str) -> bool {
        Path::new(path).extension().is_some_and(|e| e == "cs") || is_prefab(path)
    }

    fn check(
        &self,
        _ctx: &CheckCtx<'_, Crunk>,
        file: FileId,
        path: &str,
        text: &str,
    ) -> Vec<Finding> {
        let Ok(id) = Gx014.meta().rule_id() else {
            return Vec::new();
        };
        let hits = if is_prefab(path) {
            prefab_literals(text)
        } else {
            literals(text)
        };
        hits.into_iter()
            .map(|hit| {
                tracing::debug!(
                    path,
                    offset = hit.offset,
                    "GX014: literal in prefab generator"
                );
                let start = TextSize::new(u32::try_from(hit.offset).unwrap_or(u32::MAX));
                let len = TextSize::new(u32::try_from(hit.len).unwrap_or(0));
                let span = Span::new(file, TextRange::at(start, len));
                if hit.unresolved {
                    return Finding::new(
                        id.clone(),
                        Severity::Unresolved,
                        Some(span),
                        hit.message,
                        path,
                    )
                    .with_reason(UnresolvedReason::from_code(hit.reason));
                }
                Finding::new(id.clone(), Severity::Error, Some(span), hit.message, path)
            })
            .collect()
    }
}
