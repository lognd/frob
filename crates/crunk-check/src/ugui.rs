//! GX014: a prefab generator (C# that writes uGUI prefabs) must take colours and font sizes from
//! the generated token constants (`crunk export csharp`), never from literals (crunk.md section 7).
//!
//! The check is a [`FileCheck`] over `.cs` files: only files that call `PrefabUtility.` are
//! generators, the generated token class itself (it carries the `GENERATED` banner) is exempt,
//! and comments and string contents are never scanned. The prefab YAML is not a walked language,
//! so its read-only audit is a follow-up (see the design note in crunk.md section 7).

// frob:ticket 01M4CXSD8DEYB69E5J7Q1ABGXK

use std::path::Path;

use gob_check::{CheckCtx, FileCheck, SharedCtx};
use gob_rules::{Finding, Rule, RuleMeta, Severity};
use gob_text::{FileId, Span, TextRange, TextSize};

use crate::Crunk;

/// A uGUI prefab generator holds a colour or font-size literal instead of a generated token.
#[derive(Debug, Clone, Copy, Default, Rule)]
#[rule(
    id = "GX014",
    slug = "ugui-literal-not-token",
    family = "GX",
    product = "crunk",
    severity = Error,
    tier = Universal,
    scope = File,
    fix = Manual,
    version = 1
)]
pub struct Gx014;

/// Named `UnityEngine.Color` statics that are literals in disguise (`Color.clear` is not).
const NAMED_COLORS: [&str; 10] = [
    "white", "black", "red", "green", "blue", "yellow", "cyan", "magenta", "gray", "grey",
];

/// Names of the banners a generated token file carries (`CSHARP_BANNER` and the `<auto-generated` form).
const GENERATED_MARKERS: [&str; 2] = ["GENERATED", "<auto-generated"];

/// The [`FileCheck`] that emits [`Gx014`] over `.cs` prefab generators.
#[derive(Debug, Clone, Copy, Default)]
pub struct UguiLiteralCheck;

/// One literal found in a generator: byte range and what to tell the author.
#[derive(Debug, PartialEq, Eq)]
pub(crate) struct Hit {
    /// Byte offset of the literal.
    pub offset: usize,
    /// Byte length of the flagged text.
    pub len: usize,
    /// The finding message.
    pub message: String,
}

/// `text` with comments (and, when `strings`, string/char literal contents) blanked to spaces,
/// keeping every byte offset and newline.
fn mask(text: &str, strings: bool) -> String {
    let b = text.as_bytes();
    let mut out = b.to_vec();
    let blank = |out: &mut [u8], from: usize, to: usize| {
        for byte in &mut out[from..to] {
            if *byte != b'\n' {
                *byte = b' ';
            }
        }
    };
    let mut i = 0;
    while i < b.len() {
        match b[i] {
            b'/' if b.get(i + 1) == Some(&b'/') => {
                let end = text[i..].find('\n').map_or(b.len(), |n| i + n);
                blank(&mut out, i, end);
                i = end;
            }
            b'/' if b.get(i + 1) == Some(&b'*') => {
                let end = text[i + 2..].find("*/").map_or(b.len(), |n| i + 2 + n + 2);
                blank(&mut out, i, end);
                i = end;
            }
            q @ (b'"' | b'\'') => {
                let mut j = i + 1;
                while j < b.len() && b[j] != q && b[j] != b'\n' {
                    j += if b[j] == b'\\' { 2 } else { 1 };
                }
                let end = j.min(b.len());
                if strings {
                    blank(&mut out, i + 1, end);
                }
                i = (end + 1).min(b.len());
            }
            _ => i += 1,
        }
    }
    String::from_utf8(out).unwrap_or_default()
}

/// True when `c` can continue a C# identifier.
fn is_ident(c: u8) -> bool {
    c.is_ascii_alphanumeric() || c == b'_'
}

/// True when `args` is made only of numeric literals and arithmetic on them.
fn all_numeric(args: &str) -> bool {
    let b = args.as_bytes();
    !args.trim().is_empty()
        && b.iter().enumerate().all(|(i, &c)| match c {
            b'0'..=b'9' | b'.' | b',' | b'+' | b'-' | b'*' | b'/' | b'(' | b')' => true,
            c if c.is_ascii_whitespace() => true,
            b'f' | b'F' | b'd' | b'D' => i > 0 && (b[i - 1].is_ascii_digit() || b[i - 1] == b'.'),
            _ => false,
        })
}

/// The matching close paren of the `(` at `open` in `code`.
fn close_paren(code: &str, open: usize) -> Option<usize> {
    let mut depth = 0usize;
    for (i, c) in code.bytes().enumerate().skip(open) {
        match c {
            b'(' => depth += 1,
            b')' => {
                depth -= 1;
                if depth == 0 {
                    return Some(i);
                }
            }
            _ => {}
        }
    }
    None
}

/// Every colour and font-size literal of a prefab generator `text` (empty for other files).
pub(crate) fn literals(text: &str) -> Vec<Hit> {
    let head: String = text.lines().take(8).collect::<Vec<_>>().join("\n");
    if GENERATED_MARKERS.iter().any(|m| head.contains(m)) {
        tracing::debug!("GX014: generated token file, exempt");
        return Vec::new();
    }
    let code = mask(text, true);
    if !code.contains("PrefabUtility.") {
        return Vec::new();
    }
    let mut hits = Vec::new();
    for ctor in ["new Color(", "new Color32("] {
        for (at, _) in code.match_indices(ctor) {
            let open = at + ctor.len() - 1;
            let Some(close) = close_paren(&code, open) else {
                continue;
            };
            if all_numeric(&code[open + 1..close]) {
                hits.push(Hit {
                    offset: at,
                    len: close + 1 - at,
                    message: format!(
                        "colour literal `{}` in a prefab generator; use the generated token constant (`crunk export csharp`) instead",
                        text[at..=close].split_whitespace().collect::<Vec<_>>().join(" ")
                    ),
                });
            }
        }
    }
    for (at, _) in code.match_indices("Color.") {
        let before_ok =
            at == 0 || !(is_ident(code.as_bytes()[at - 1]) || code.as_bytes()[at - 1] == b'.');
        let rest = &code[at + 6..];
        let word: String = rest
            .chars()
            .take_while(char::is_ascii_alphanumeric)
            .collect();
        if before_ok && NAMED_COLORS.contains(&word.as_str()) {
            hits.push(Hit {
                offset: at,
                len: 6 + word.len(),
                message: format!(
                    "named colour `Color.{word}` in a prefab generator; use the generated token constant (`crunk export csharp`) instead"
                ),
            });
        }
    }
    let with_strings = mask(text, false);
    for (at, _) in with_strings.match_indices("TryParseHtmlString(") {
        let rest = with_strings[at + 19..].trim_start();
        if rest.starts_with("\"#") {
            hits.push(Hit {
                offset: at,
                len: 19,
                message: "hex colour literal in a prefab generator; use the generated token constant (`crunk export csharp`) instead".to_owned(),
            });
        }
    }
    for (at, _) in code.match_indices("fontSize") {
        let b = code.as_bytes();
        if at > 0 && is_ident(b[at - 1]) {
            continue;
        }
        let rest = code[at + 8..].trim_start();
        let Some(rest) = rest.strip_prefix('=') else {
            continue;
        };
        if rest.starts_with('=') {
            continue;
        }
        let num: String = rest
            .trim_start()
            .chars()
            .take_while(|c| c.is_ascii_digit() || *c == '.')
            .collect();
        let after = rest.trim_start()[num.len()..].trim_start_matches(['f', 'F']);
        if !num.is_empty() && !after.starts_with(|c: char| is_ident(c as u8)) {
            hits.push(Hit {
                offset: at,
                len: 8,
                message: format!(
                    "font-size literal `{num}` in a prefab generator; use the generated token constant (`crunk export csharp`) instead"
                ),
            });
        }
    }
    hits.sort_by_key(|h| h.offset);
    hits
}

impl FileCheck<Crunk> for UguiLiteralCheck {
    fn rules(&self) -> Vec<&'static RuleMeta> {
        vec![Gx014.meta()]
    }

    fn applies(&self, _ctx: &SharedCtx<'_, Crunk>, path: &str) -> bool {
        Path::new(path).extension().is_some_and(|e| e == "cs")
    }

    fn check(
        &self,
        _ctx: &CheckCtx<'_, Crunk>,
        file: FileId,
        path: &str,
        text: &str,
    ) -> Vec<Finding> {
        let Ok(id) = Gx014.meta().rule_id() else {
            return Vec::new();
        };
        literals(text)
            .into_iter()
            .map(|hit| {
                tracing::debug!(
                    path,
                    offset = hit.offset,
                    "GX014: literal in prefab generator"
                );
                let start = TextSize::new(u32::try_from(hit.offset).unwrap_or(u32::MAX));
                let len = TextSize::new(u32::try_from(hit.len).unwrap_or(0));
                let span = Span::new(file, TextRange::at(start, len));
                Finding::new(id.clone(), Severity::Error, Some(span), hit.message, path)
            })
            .collect()
    }
}
