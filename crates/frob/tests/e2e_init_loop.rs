/// `frob check` before `frob init` refuses and names `frob init` (diagnostics.md section 5, ~ANDZXZ4).
// frob:ticket 01M40FXV09GYGBH9YZZANDZXZ4
#[test]
fn check_before_init_says_to_run_init() {
    let repo = Fresh::new("main");
    let out = Fresh::run_in(&repo.root, &["--text", "check"]);
    let all = format!(
        "{}{}",
        String::from_utf8_lossy(&out.stdout),
        String::from_utf8_lossy(&out.stderr)
    );
    assert!(
        code(&out) != 0 && all.contains("frob init") && !all.contains("DRIFT001"),
        "~ANDZXZ4: check without frob.toml must refuse and name `frob init`, exit {} output: {all}",
        code(&out)
    );
}

/// A fresh initialized repository passes `frob check`: REF001 and TODO002 have nothing to judge (~VA936C5).
// frob:ticket 01M4069Z0HH5RV8TNPFVA936C5
#[test]
fn check_after_init_on_a_fresh_repository_passes() {
    let repo = Fresh::new("main");
    repo.init_committed();
    let out = Fresh::frob(&repo.root, &["check"]);
    assert_eq!(
        code(&out),
        0,
        "~VA936C5: {}",
        json(&out)["error"]["message"]
    );
}

/// A usage error for missing required arguments names each of them and carries a usage line.
// frob:ticket 01M40FXV4AB47ASH79KJNF3JFH
#[test]
fn usage_error_names_the_missing_arguments() {
    let repo = Fresh::new("main");
    // `ticket evidence add` takes `--ref` only for non-attestation providers (checked after parsing), so two clap-required arguments come from `milestone new`.
    let out = Fresh::frob(&repo.root, &["milestone", "new"]);
    let error = json(&out)["error"].clone();
    let msg = error["message"].as_str().expect("message").to_owned();
    assert!(
        msg.contains("--goal") && msg.contains("<VERSION>"),
        "usage error message is `{msg}`"
    );
    let remedy = error["remedy"].as_str().expect("remedy");
    assert!(remedy.contains("usage:"), "remedy is `{remedy}`");
}
