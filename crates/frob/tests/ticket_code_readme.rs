//! `frob ticket reindex --code-readme`: the marked README region and its GEN001 check (`navigation.md` 3.2).
// frob:ticket 01M3ZX87403VR4YVK4QMJ7KPBV

use std::path::Path;
use std::process::Output;

mod common;

fn frob(cwd: &Path, args: &[&str]) -> Output {
    common::frob_command()
        .current_dir(cwd)
        .env_remove("FROB_LOG")
        .args(args)
        .output()
        .expect("run frob")
}

fn git(cwd: &Path, args: &[&str]) {
    let out = std::process::Command::new("git")
        .args(args)
        .current_dir(cwd)
        .output()
        .expect("git");
    assert!(out.status.success(), "{args:?}");
}

const BEGIN: &str =
    "<!-- GENERATED by frob: BEGIN tickets. Regenerate: frob ticket reindex --code-readme -->";
const END: &str = "<!-- GENERATED by frob: END tickets -->";

/// A repository with a ticket branch and a README that has hand-written text around a stale region.
fn fixture() -> tempfile::TempDir {
    let dir = common::git_repo();
    let p = dir.path();
    std::fs::write(
        p.join("README.md"),
        format!("# Demo\n\nhand-written intro\n\n{BEGIN}\nstale\n{END}\n\nhand-written tail\n"),
    )
    .expect("readme");
    std::fs::write(p.join("frob.toml"), "[tickets]\nref_mode = \"orphan\"\n").expect("config");
    git(p, &["add", "-A"]);
    git(p, &["commit", "-qm", "code"]);
    let init = frob(p, &["ticket", "branch", "init"]);
    assert_eq!(init.status.code(), Some(0));
    dir
}

fn readme(p: &Path) -> String {
    std::fs::read_to_string(p.join("README.md")).expect("read")
}

#[test]
fn code_readme_changes_only_the_marked_region() {
    let dir = fixture();
    let p = dir.path();
    let before = readme(p);
    let out = frob(p, &["ticket", "reindex", "--code-readme"]);
    assert_eq!(
        out.status.code(),
        Some(0),
        "{}",
        String::from_utf8_lossy(&out.stdout)
    );
    let after = readme(p);
    let (head, rest) = before.split_once(BEGIN).expect("begin");
    let (_, tail) = rest.split_once(END).expect("end");
    assert!(after.starts_with(head) && after.ends_with(tail), "{after}");
    assert!(
        after.contains("frob-tickets") && after.contains("frob work ~HANDLE"),
        "{after}"
    );
    assert!(!after.contains("stale"));
    let again = frob(p, &["ticket", "reindex", "--code-readme", "--check"]);
    assert_eq!(again.status.code(), Some(0), "second run is current");
}

#[test]
fn a_hand_edit_inside_the_region_fails_check_with_gen001() {
    let dir = fixture();
    let p = dir.path();
    assert_eq!(
        frob(p, &["ticket", "reindex", "--code-readme"])
            .status
            .code(),
        Some(0)
    );
    std::fs::write(
        p.join("README.md"),
        readme(p).replace("start it", "begin it"),
    )
    .expect("edit");
    let out = frob(p, &["ticket", "reindex", "--code-readme", "--check"]);
    assert_eq!(out.status.code(), Some(1));
    let text =
        String::from_utf8_lossy(&out.stdout).into_owned() + &String::from_utf8_lossy(&out.stderr);
    assert!(text.contains("GEN001"), "{text}");
    assert!(readme(p).contains("begin it"), "--check must not write");
}
