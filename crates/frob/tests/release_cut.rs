#[test]
fn a_cut_that_fails_between_the_tags_resumes_with_no_second_commit() {
    // frob:tests crates/frob/src/release_cmd.rs::ReleaseCut.run
    // frob:tests crates/frob-release/src/cut.rs::cut
    let repo = releasable(true);
    let d = repo.dir.path();
    // A ref below the grimble tag name makes that tag impossible to create, after the frob tag exists.
    git(d, &["tag", "grimble-v0.532.0/blocker"]);
    let out = repo.frob(&["release", "cut", "0.532.0"]);
    assert_ne!(code(&out), 0, "{}", String::from_utf8_lossy(&out.stdout));
    let commit = git_out(d, &["rev-parse", "frob-v0.532.0^{commit}"]);
    assert_eq!(
        git_out(d, &["rev-parse", "main"]),
        commit,
        "the commit stands"
    );
    assert!(
        !milestone_events(&repo).contains("kind = \"cut\""),
        "nothing recorded yet"
    );
    git(d, &["tag", "-d", "grimble-v0.532.0/blocker"]);
    let v = repo.ok(&["release", "cut", "0.532.0"]);
    assert_eq!(v["data"]["resumed"], true);
    assert_eq!(v["data"]["commit"], commit.as_str());
    assert_eq!(
        git_out(d, &["rev-parse", "grimble-v0.532.0^{commit}"]),
        commit
    );
    let log = git_out(d, &["log", "--format=%s", "--first-parent"]);
    assert_eq!(
        log.matches("chore(release): cut 0.532.0").count(),
        1,
        "{log}"
    );
    assert!(milestone_events(&repo).contains("kind = \"cut\""));
}

