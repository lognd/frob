//! `release cut` end to end on temporary repositories with a ledger and a milestone.
// frob:ticket 01M4069X6S9RJWRXX3YBZ9EG10

mod common;

use std::path::Path;
use std::process::Output;
use std::time::Duration;

use gob_exec::{Limits, Outcome, Program, Runner, Spec};
use serde_json::Value;

/// A trunk-mode repository with `frob init` run and one commit.
struct Repo {
    dir: tempfile::TempDir,
}

fn git(dir: &Path, args: &[&str]) {
    let spec = Spec {
        program: Program::Git,
        args: args.iter().map(|a| (*a).to_owned()).collect(),
        cwd: Some(dir.to_path_buf()),
        env: Vec::new(),
        timeout: Duration::from_secs(30),
        capture: true,
    };
    let out = Runner::new(Limits { jobs: 1 }).run(&spec).expect("run git");
    assert_eq!(
        out.status,
        Outcome::Exited(0),
        "git {args:?}: {}",
        out.stderr
    );
}

impl Repo {
    fn new() -> Self {
        let dir = tempfile::tempdir().expect("tempdir");
        git(dir.path(), &["init", "-q"]);
        git(dir.path(), &["symbolic-ref", "HEAD", "refs/heads/main"]);
        git(dir.path(), &["config", "user.name", "Test User"]);
        git(dir.path(), &["config", "user.email", "test@example.com"]);
        git(dir.path(), &["config", "core.autocrlf", "false"]);
        let repo = Self { dir };
        assert_eq!(code(&repo.run(&["--json", "init"])), 0);
        let toml = repo.dir.path().join("frob.toml");
        let text = std::fs::read_to_string(&toml).expect("frob.toml");
        std::fs::write(
            &toml,
            text.replace("require_ci = true", "require_ci = false")
                .replace("tag = \"v{version}\"", "tag = \"{product}-v{version}\"")
                .replace("products = []", "products = [\"frob\", \"grimble\"]"),
        )
        .expect("write frob.toml");
        git(repo.dir.path(), &["add", "-A"]);
        git(repo.dir.path(), &["commit", "-q", "-m", "base"]);
        repo
    }

    fn run(&self, args: &[&str]) -> Output {
        common::frob_command()
            .current_dir(self.dir.path())
            .env_remove("FROB_LOG")
            .args(args)
            .output()
            .expect("run frob")
    }

    fn frob(&self, args: &[&str]) -> Output {
        let mut a = vec!["--json"];
        a.extend_from_slice(args);
        self.run(&a)
    }

    fn ok(&self, args: &[&str]) -> Value {
        let out = self.frob(args);
        assert_eq!(
            code(&out),
            0,
            "{args:?}: {}",
            String::from_utf8_lossy(&out.stdout)
        );
        json(&out)
    }

    fn ticket(&self, ty: &str) -> String {
        self.titled(ty, "t")
    }

    fn titled(&self, ty: &str, title: &str) -> String {
        self.ok(&["ticket", "new", "--title", title, "--type", ty])["data"]["id"]
            .as_str()
            .expect("id")
            .to_owned()
    }
}

fn json(out: &Output) -> Value {
    serde_json::from_slice(&out.stdout)
        .unwrap_or_else(|e| panic!("not JSON ({e}): {}", String::from_utf8_lossy(&out.stdout)))
}

fn code(out: &Output) -> i32 {
    out.status.code().expect("exit code")
}

const ROOT: &str = "[workspace]\nmembers = [\"crates/*\"]\n\n[workspace.package]\nversion = \"0.0.0\"\nedition = \"2024\"\n";
const A: &str = "[package]\nname = \"a\"\nversion = \"0.0.0\"\nedition = \"2024\"\n";
const LOCK: &str = "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = \"a\"\nversion = \"0.0.0\"\n";

fn git_out(dir: &Path, args: &[&str]) -> String {
    let spec = Spec {
        program: Program::Git,
        args: args.iter().map(|a| (*a).to_owned()).collect(),
        cwd: Some(dir.to_path_buf()),
        env: Vec::new(),
        timeout: Duration::from_secs(30),
        capture: true,
    };
    let out = Runner::new(Limits { jobs: 1 }).run(&spec).expect("run git");
    assert_eq!(
        out.status,
        Outcome::Exited(0),
        "git {args:?}: {}",
        out.stderr
    );
    out.stdout.trim().to_owned()
}

fn write(repo: &Repo, rel: &str, text: &str) {
    let p = repo.dir.path().join(rel);
    std::fs::create_dir_all(p.parent().expect("parent")).expect("mkdir");
    std::fs::write(p, text).expect("write");
}

/// A workspace, a milestone with one criterion (bound unless `bound` is false) and one changelog fragment, all committed.
fn releasable(bound: bool) -> Repo {
    let repo = Repo::new();
    write(&repo, "Cargo.toml", ROOT);
    write(&repo, "crates/a/Cargo.toml", A);
    write(&repo, "crates/a/src/lib.rs", "");
    write(&repo, "Cargo.lock", LOCK);
    write(&repo, "proof.txt", "proof");
    repo.ok(&[
        "milestone",
        "new",
        "0.532.0",
        "--goal",
        "Ship",
        "--criterion",
        "only",
    ]);
    if bound {
        repo.ok(&[
            "milestone",
            "evidence",
            "add",
            "0.532.0",
            "--provider",
            "file",
            "--ref",
            "proof.txt",
            "--accepts",
            "1",
        ]);
    }
    let t = repo.ticket("task");
    write(
        &repo,
        &format!("changelog.d/{t}.added.md"),
        "frob: Added the cut.\n",
    );
    git(repo.dir.path(), &["add", "-A"]);
    git(repo.dir.path(), &["commit", "-q", "-m", "release inputs"]);
    repo
}

/// Every milestone event file concatenated.
fn milestone_events(repo: &Repo) -> String {
    let mut all = String::new();
    let mut stack = vec![repo.dir.path().join("tickets/_milestones")];
    while let Some(d) = stack.pop() {
        for e in std::fs::read_dir(&d).expect("readdir").flatten() {
            let p = e.path();
            if p.is_dir() {
                stack.push(p);
            } else {
                all.push_str(&std::fs::read_to_string(&p).expect("read"));
                all.push('\n');
            }
        }
    }
    all
}

#[test]
fn a_ready_milestone_is_cut_into_one_commit_with_tags_and_a_ledger_record() {
    // frob:tests crates/frob/src/release_cmd.rs::ReleaseCut.run
    // frob:tests crates/frob-release/src/cut.rs::cut
    let repo = releasable(true);
    let d = repo.dir.path();
    let before = git_out(d, &["rev-parse", "main"]);
    let v = repo.ok(&["release", "cut", "0.532.0"]);
    let commit = v["data"]["commit"].as_str().expect("commit").to_owned();
    assert_eq!(
        git_out(d, &["rev-parse", &format!("{commit}^")]),
        before,
        "one commit on the old base"
    );
    let files = git_out(d, &["show", "--name-only", "--format=", &commit]);
    let files: Vec<&str> = files.lines().collect();
    assert_eq!(files.len(), 5, "{files:?}");
    assert!(
        files.contains(&"CHANGELOG.md")
            && files.contains(&"Cargo.toml")
            && files.contains(&"Cargo.lock")
    );
    assert!(
        files.iter().any(|f| f.starts_with("changelog.d/")),
        "the fragment removal is in the commit"
    );
    assert!(
        !d.join("changelog.d")
            .read_dir()
            .is_ok_and(|mut r| r.next().is_some()),
        "fragments gone"
    );
    assert!(
        std::fs::read_to_string(d.join("CHANGELOG.md"))
            .expect("changelog")
            .contains("Added the cut.")
    );
    for tag in ["frob-v0.532.0", "grimble-v0.532.0"] {
        assert_eq!(
            git_out(d, &["rev-parse", &format!("{tag}^{{commit}}")]),
            commit,
            "{tag}"
        );
        assert_eq!(git_out(d, &["cat-file", "-t", tag]), "tag", "annotated");
    }
    assert_eq!(v["data"]["tags"].as_array().expect("tags").len(), 2);
    assert_eq!(v["data"]["pushed"], false);
    let events = milestone_events(&repo);
    assert!(
        events.contains("kind = \"cut\"") && events.contains(&commit),
        "{events}"
    );
    assert!(events.contains("to = \"released\""), "{events}");
    let shown = repo.ok(&["milestone", "show", "0.532.0"]);
    assert_eq!(shown["data"]["milestone"]["state"], "released", "{shown}");
    assert_eq!(
        code(&repo.frob(&["release", "cut", "0.532.0"])),
        3,
        "a recorded cut is not repeated"
    );
}

