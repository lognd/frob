//! `TICK006`: hand-written text that links a ticket-branch path is flagged and rewritten to the ULID.
// frob:ticket 01M3ZX86MA30ABW915Z943BQYB

use std::path::Path;
use std::process::Output;

use serde_json::Value;

use crate::common;

fn frob(cwd: &Path, args: &[&str]) -> Output {
    common::frob_command()
        .current_dir(cwd)
        .env_remove("FROB_LOG")
        .args(args)
        .output()
        .expect("run frob")
}

fn json(cwd: &Path, args: &[&str]) -> Value {
    let out = frob(cwd, args);
    serde_json::from_slice(&out.stdout).unwrap_or_else(|e| {
        panic!(
            "{args:?}: {e}: {}{}",
            String::from_utf8_lossy(&out.stdout),
            String::from_utf8_lossy(&out.stderr)
        )
    })
}

fn git(cwd: &Path, args: &[&str]) {
    let st = std::process::Command::new("git")
        .args(args)
        .current_dir(cwd)
        .status()
        .expect("git");
    assert!(st.success(), "git {args:?}");
}

/// A ticket-branch repository with a task "Parser rewrite" (at `_unfiled/parser-rewrite.md`) and its ULID.
fn fixture(doc: &str) -> (tempfile::TempDir, String) {
    let dir = common::git_repo();
    let p = dir.path();
    std::fs::write(p.join("frob.toml"), "[tickets]\nref_mode = \"orphan\"\n").expect("config");
    std::fs::create_dir_all(p.join("docs")).expect("docs");
    std::fs::write(p.join("docs/note.md"), doc).expect("doc");
    git(p, &["add", "-A"]);
    git(p, &["commit", "-qm", "code"]);
    json(p, &["ticket", "branch", "init"]);
    let id = json(p, &["ticket", "new", "--title", "Parser rewrite"])["data"]["id"]
        .as_str()
        .expect("id")
        .to_owned();
    (dir, id)
}

fn tick006(p: &Path) -> Vec<Value> {
    json(p, &["check", "--json", "--fail-on", "none"])["data"]["findings"]
        .as_array()
        .expect("findings")
        .iter()
        .filter(|f| f["rule"] == "TICK006")
        .cloned()
        .collect()
}

#[test]
fn a_ticket_branch_url_and_a_bare_ticket_path_fire_and_fix_rewrites_both_to_the_ulid() {
    let doc = "See https://github.com/o/r/blob/frob-tickets/_unfiled/parser-rewrite.md for the plan\n\
               and _unfiled/parser-rewrite.md too.\n";
    let (dir, id) = fixture(doc);
    let p = dir.path();
    assert_eq!(tick006(p).len(), 2, "one finding per link");

    json(p, &["check", "--json", "--fail-on", "none", "--fix"]);
    let fixed = std::fs::read_to_string(p.join("docs/note.md")).expect("read");
    assert_eq!(fixed, format!("See {id} for the plan\nand {id} too.\n"));
    assert!(tick006(p).is_empty(), "clean after the fix");
}

#[test]
fn generated_pages_and_non_ticket_markdown_links_do_not_fire() {
    let doc = "<!-- GENERATED by frob v1: DO NOT EDIT -->\n_unfiled/parser-rewrite.md\n";
    let (dir, _id) = fixture(doc);
    let p = dir.path();
    std::fs::write(p.join("docs/other.md"), "see docs/design/x.md and a/b.md\n").expect("write");
    assert!(tick006(p).is_empty());
}

#[test]
fn a_ticket_body_linking_a_ticket_path_fires_on_the_ledger_file_without_a_fix() {
    // frob:ticket 01M4P8M16T2T3Y311ER1Z77KSE
    let (dir, _id) = fixture("plain\n");
    let p = dir.path();
    json(
        p,
        &[
            "ticket",
            "new",
            "--title",
            "Follow up",
            "--body",
            "See _unfiled/parser-rewrite.md for context.",
        ],
    );
    let found = tick006(p);
    assert_eq!(found.len(), 1, "{found:?}");
    assert!(
        found[0]["message"]
            .as_str()
            .is_some_and(|m| m.contains("_unfiled/follow-up.md") || m.contains("parser-rewrite.md")),
        "{found:?}"
    );
    assert!(found[0]["fix"].is_null(), "ledger files carry no fix");
}
