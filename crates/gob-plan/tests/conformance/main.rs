//! Conformance: every compiled-in std rule equals its plan byte for byte (plugins.md 6.1,
//! security.md 2.8). The compiled-in side is the generated Rust module; the plan side is the
//! checked-in `.plan` run by the interpreter; both are also checked against the GRL source.

// frob:ticket 01M3ZX7HRM8SVB3607V973VQTH

mod compare;
mod corpus;

use compare::{Case, Divergence, Runner, conform, interpret};
use gob_plan::lower::lower_rule;
use gob_plan::plan::{Plan, Provenance};

#[allow(dead_code)]
#[path = "../../../../packs/std/generated/todo001.rs"]
mod todo001;

/// One compiled-in rule: its id, its embedded plan bytes and its entry point.
struct Compiled {
    id: &'static str,
    bytes: &'static [u8],
    run: fn(
        &gob_plan::exec::Input<'_>,
        &gob_plan::exec::relations::Relations,
    ) -> Result<gob_plan::exec::outcome::Outcomes, String>,
}

fn compiled() -> Vec<Compiled> {
    vec![Compiled {
        id: "TODO001",
        bytes: &todo001::PLAN_BYTES,
        run: |i, r| todo001::run(i, r).map_err(|e| format!("{e:?}")),
    }]
}

fn rule_source(id: &str) -> String {
    let p = corpus::root()
        .join("packs/std/rules")
        .join(format!("{id}.grl"));
    std::fs::read_to_string(&p).unwrap_or_else(|e| panic!("{}: {e}", p.display()))
}

fn plan_file(id: &str) -> Plan {
    let p = corpus::root()
        .join("packs/std/plans")
        .join(format!("{id}.plan"));
    let bytes = std::fs::read(&p).unwrap_or_else(|e| panic!("{}: {e}", p.display()));
    Plan::load(&bytes).unwrap_or_else(|e| panic!("{}: {e:?}", p.display()))
}

fn lowered(id: &str) -> (gob_plan::grl::ast::Rule, Plan) {
    let parsed = gob_plan::grl::parse(
        gob_text::FileInterner::new().intern("r.grl"),
        &rule_source(id),
    );
    assert!(parsed.is_ok(), "{id}: {:?}", parsed.errors);
    let rule = parsed.file.rules.into_iter().next().expect("one rule");
    let plan = lower_rule(&rule, Provenance::Std).expect("lowers");
    (rule, plan)
}

fn run_all(id: &str, cases: &[Case], c: Runner<'_>, p: Runner<'_>) -> Result<usize, Divergence> {
    let mut findings = 0;
    for case in cases {
        findings += conform(id, case, c, p)?;
    }
    Ok(findings)
}

// frob:tests crates/gob-plan/src/codegen/mod.rs::generate
#[test]
fn every_std_rule_source_has_a_compiled_in_module() {
    let dir = corpus::root().join("packs/std/rules");
    let mut on_disk: Vec<String> = std::fs::read_dir(dir)
        .unwrap()
        .filter_map(|e| {
            e.ok()?
                .path()
                .file_stem()
                .map(|s| s.to_string_lossy().into_owned())
        })
        .collect();
    on_disk.sort();
    let mut known: Vec<String> = compiled().iter().map(|c| c.id.to_owned()).collect();
    known.sort();
    assert_eq!(
        on_disk, known,
        "register each generated module in compiled()"
    );
}

// frob:tests crates/gob-plan/src/codegen/mod.rs::generate
#[test]
fn compiled_in_plan_bytes_equal_the_plan_file_and_a_fresh_lowering() {
    for c in compiled() {
        let (_, fresh) = lowered(c.id);
        assert_eq!(
            c.bytes,
            fresh.to_bytes().as_slice(),
            "{}: generated bytes",
            c.id
        );
        assert_eq!(
            c.bytes,
            plan_file(c.id).to_bytes().as_slice(),
            "{}: .plan file",
            c.id
        );
    }
}

// frob:tests crates/gob-plan/src/exec/outcome/mod.rs::outcomes
#[test]
fn compiled_in_and_plan_json_are_identical_on_the_std_corpus_and_examples() {
    for c in compiled() {
        let (rule, _) = lowered(c.id);
        let plan = plan_file(c.id);
        let mut cases = corpus::examples(&rule);
        assert!(!cases.is_empty(), "{}: no examples to run", c.id);
        cases.extend(corpus::std_corpus());
        let run = c.run;
        let interp = interpret(&plan);
        let n = run_all(c.id, &cases, &run, &interp).unwrap_or_else(|d| panic!("{d}"));
        assert!(n > 0, "{}: the corpus never made the rule fire", c.id);
    }
}

// frob:tests crates/gob-plan/src/exec/outcome/mod.rs::outcomes
#[test]
fn compiled_in_and_plan_json_are_identical_on_an_adversarial_corpus() {
    for c in compiled() {
        let plan = plan_file(c.id);
        let run = c.run;
        let interp = interpret(&plan);
        for seed in [1, 7, 0x5eed] {
            run_all(c.id, &corpus::adversarial(seed, 40), &run, &interp)
                .unwrap_or_else(|d| panic!("{d}"));
        }
    }
}

// frob:tests crates/gob-plan/src/exec/outcome/mod.rs::outcomes
#[test]
fn a_divergent_generated_rule_fails_naming_the_rule_and_the_first_differing_finding() {
    let c = &compiled()[0];
    let (rule, _) = lowered(c.id);
    // The "generated" side is a different rule body under the same id: it drops the `no`.
    let edited = rule_source(c.id).replace("  no d: directive \"todo\" where d adjoins c\n", "");
    assert_ne!(edited, rule_source(c.id));
    let parsed = gob_plan::grl::parse(gob_text::FileInterner::new().intern("r.grl"), &edited);
    assert!(parsed.is_ok(), "{:?}", parsed.errors);
    let divergent = lower_rule(&parsed.file.rules[0], Provenance::Std).unwrap();
    let real = plan_file(c.id);
    let (bad, good) = (interpret(&divergent), interpret(&real));
    let err = run_all(c.id, &corpus::examples(&rule), &bad, &good).unwrap_err();
    let msg = err.to_string();
    assert!(msg.contains("TODO001"), "{msg}");
    assert!(msg.contains("first differing finding #"), "{msg}");
}
