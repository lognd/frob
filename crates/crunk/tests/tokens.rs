use std::path::Path;

use gob_cli::run_for_test;
use serde_json::Value;

const SPEC: &str = r##"[project]
css_root = "styles"
tokens_file = "tokens.css"
root_font_size = 16

[palette]
ink = "#1a1a1a"
paper = "#fafaf7"

[scales]
spacing = [0, 4, 8]
font_sizes = [12, 16]
radii = [0, 4]

[typography]
families = ["Inter", "sans-serif"]
weights = [400, 700]

[layers]
base = 0

[org]
buckets = ["base", "components", "layouts", "utilities"]
class_case = "kebab"
component_prefix = true
tokens_only_custom_props = true

[lint]
SPACE001 = "warn"
fix_tolerance = 0.15
color_tolerance = 8.0

[tokens]
json_file = "tokens.json"

[tailwind]
tokens_file = "tailwind.tokens.json"
"##;

fn crunk(dir: &Path, args: &[&str]) -> (i32, Value, String) {
    let (code, out, err) = run_for_test(&crunk::cli(), args, dir);
    (code, serde_json::from_str(&out).unwrap_or(Value::Null), err)
}

fn project() -> tempfile::TempDir {
    let dir = tempfile::tempdir().expect("tempdir");
    std::fs::write(dir.path().join("crunk.toml"), SPEC).unwrap();
    dir
}

// frob:tests crates/crunk/src/tokens.rs::Tokens
#[test]
fn bare_tokens_writes_every_file_and_check_is_then_clean() {
    let dir = project();
    let (code, env, _) = crunk(dir.path(), &["tokens", "--json"]);
    assert_eq!(code, 0, "{env}");
    for rel in ["styles/tokens.css", "tokens.json", "tailwind.tokens.json"] {
        assert!(dir.path().join(rel).is_file(), "{rel} not written");
    }
    let css = std::fs::read_to_string(dir.path().join("styles/tokens.css")).unwrap();
    assert!(css.contains("GENERATED by crunk tokens"), "{css}");
    let (code, env, _) = crunk(dir.path(), &["tokens", "--check", "--json"]);
    assert_eq!(code, 0, "{env}");
}

// frob:tests crates/crunk/src/tokens.rs::Tokens
#[test]
fn hand_edited_tokens_css_fails_check_and_names_the_file() {
    let dir = project();
    crunk(dir.path(), &["tokens", "--json"]);
    let css = dir.path().join("styles/tokens.css");
    let mut text = std::fs::read_to_string(&css).unwrap();
    text.push_str("/* hand edit */\n");
    std::fs::write(&css, text).unwrap();
    let (code, env, err) = crunk(dir.path(), &["tokens", "--check", "--json"]);
    assert_eq!(code, 1, "{env} {err}");
    let shown = format!("{env}{err}");
    assert!(shown.contains("styles/tokens.css"), "{shown}");
    assert!(shown.contains("drifted"), "{shown}");
}

// frob:tests crates/crunk/src/tokens.rs::Tokens
#[test]
fn missing_file_fails_check() {
    let dir = project();
    let (code, env, err) = crunk(dir.path(), &["tokens", "--check", "--json"]);
    assert_eq!(code, 1, "{env} {err}");
    assert!(format!("{env}{err}").contains("missing"));
}

// frob:tests crates/crunk/src/tokens.rs::Tokens
#[test]
fn target_json_previews_and_writes_nothing() {
    let dir = project();
    let (code, env, _) = crunk(dir.path(), &["tokens", "--target", "json", "--json"]);
    assert_eq!(code, 0, "{env}");
    assert_eq!(env["data"]["preview"], "json");
    assert!(!dir.path().join("tokens.json").exists());
    assert!(!dir.path().join("styles").exists());
}

// frob:tests crates/crunk/src/tokens.rs::Tokens
#[test]
fn unknown_target_is_a_usage_error() {
    let dir = project();
    let (code, _, _) = crunk(dir.path(), &["tokens", "--target", "scss", "--json"]);
    assert_eq!(code, 2);
}
