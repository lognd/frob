// frob:ticket 01M43ATD7ZGTNCY5036AYEJR7P

use std::path::Path;

use gob_cli::run_for_test;

mod common;

fn crunk(dir: &Path, args: &[&str]) -> (i32, String, String) {
    run_for_test(&crunk::cli(), args, dir)
}

fn vite_project() -> tempfile::TempDir {
    let dir = tempfile::tempdir().expect("tempdir");
    std::fs::write(
        dir.path().join("package.json"),
        r#"{"devDependencies":{"vite":"^5.0.0"}}"#,
    )
    .expect("package.json");
    std::fs::create_dir(dir.path().join("src")).expect("src");
    std::fs::write(dir.path().join("src/main.js"), "console.log(1)\n").expect("main.js");
    dir
}

// frob:tests crates/crunk/src/init/mod.rs::Init
#[test]
fn init_in_empty_vite_project_then_check_exits_zero() {
    let dir = vite_project();
    let (code, out, err) = crunk(dir.path(), &["init"]);
    assert_eq!(code, 0, "init: {out} {err}");
    for path in [
        "crunk.toml",
        "styles/tokens.css",
        "styles/base/reset.css",
        "styles/base/.gitkeep",
        "styles/utilities/.gitkeep",
    ] {
        assert!(dir.path().join(path).is_file(), "missing {path}");
    }
    common::satisfy_craft(dir.path());
    let (code, out, err) = crunk(dir.path(), &["check"]);
    assert_eq!(code, 0, "check: {out} {err}");
}

// frob:tests crates/crunk/src/init/scaffold.rs::scaffold
