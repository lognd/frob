// frob:tests crates/crunk/src/init/detect.rs::detect
#[test]
fn detection_appends_jsx_and_tailwind_sections_that_validate() {
    let dir = vite_project();
    std::fs::write(
        dir.path().join("src/App.tsx"),
        "export const A = () => null;\n",
    )
    .expect("tsx");
    std::fs::write(
        dir.path().join("tailwind.config.ts"),
        "export default {};\n",
    )
    .expect("tw");
    let (code, out, err) = crunk(dir.path(), &["init"]);
    assert_eq!(code, 0, "init: {out} {err}");
    let text = std::fs::read_to_string(dir.path().join("crunk.toml")).expect("read");
    assert!(text.contains("[jsx]\nglobs = [\"src/**/*.tsx\"]"), "{text}");
    assert!(
        text.contains("[tailwind]\nconfig = \"tailwind.config.ts\""),
        "{text}"
    );
    let spec = crunk_spec::load_spec(dir.path()).expect("generated spec validates");
    assert_eq!(spec.jsx.globs, ["src/**/*.tsx"]);
    assert_eq!(spec.tailwind.config, "tailwind.config.ts");
}

// frob:tests crates/crunk/src/init/detect.rs::detect
#[test]
fn plain_project_gets_no_detected_sections() {
    let dir = vite_project();
    assert_eq!(crunk(dir.path(), &["init"]).0, 0);
    let text = std::fs::read_to_string(dir.path().join("crunk.toml")).expect("read");
    assert!(
        !text.lines().any(|l| l == "[jsx]" || l == "[tailwind]"),
        "{text}"
    );
}
