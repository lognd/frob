// frob:tests crates/crunk/src/init/scaffold.rs::scaffold
#[test]
fn reinit_without_force_is_usage_error_and_force_succeeds() {
    let dir = tempfile::tempdir().expect("tempdir");
    assert_eq!(crunk(dir.path(), &["init"]).0, 0);
    std::fs::write(dir.path().join("crunk.toml"), "# mine\n").expect("edit");
    let (code, out, _) = crunk(dir.path(), &["init"]);
    assert_eq!(code, 2, "{out}");
    assert!(out.contains("use --force"), "{out}");
    assert_eq!(
        std::fs::read_to_string(dir.path().join("crunk.toml")).expect("read"),
        "# mine\n",
        "refused init must not write"
    );
    assert_eq!(crunk(dir.path(), &["init", "--force"]).0, 0);
    common::satisfy_craft(dir.path());
    assert_eq!(crunk(dir.path(), &["check"]).0, 0);
}

