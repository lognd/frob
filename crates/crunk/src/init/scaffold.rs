//! Writing the `init` scaffold: config, bucket dirs, starter reset and the token files.

// frob:ticket 01M43ATD7ZGTNCY5036AYEJR7P

use std::path::{Path, PathBuf};

use super::InitData;
use super::detect;

/// The starter reset written to `<css_root>/base/reset.css`.
pub const RESET_CSS: &str = "/* GENERATED by crunk init -- starter reset, safe to edit. */\n\
*, *::before, *::after {\n  box-sizing: border-box;\n}\n\n\
body {\n  margin: 0;\n  font-family: var(--font-family-base);\n  color: var(--color-ink);\n  background: var(--color-paper);\n}\n";

/// Why a scaffold could not be written.
#[derive(Debug, thiserror::Error)]
pub enum InitError {
    /// `crunk.toml` exists and `--force` was not given.
    #[error("crunk.toml already present; use --force")]
    Exists,
    /// The preset name is not one of the bundled presets.
    #[error("unknown preset `{0}`")]
    Preset(String),
    /// The generated config did not validate (a bug in the preset or detection).
    #[error("generated crunk.toml is invalid: {0}")]
    Spec(String),
    /// The token files could not be rendered or written.
    #[error("{0}")]
    Tokens(String),
    /// A file or directory could not be written.
    #[error("cannot write {}: {source}", path.display())]
    Io {
        /// The path.
        path: PathBuf,
        /// The OS error.
        #[source]
        source: std::io::Error,
    },
}

fn io(path: &Path) -> impl FnOnce(std::io::Error) -> InitError + '_ {
    move |source| InitError::Io {
        path: path.to_path_buf(),
        source,
    }
}

fn write_file(path: &Path, text: &str) -> Result<(), InitError> {
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent).map_err(io(parent))?;
    }
    std::fs::write(path, text).map_err(io(path))?;
    tracing::info!(path = %path.display(), "init: wrote");
    Ok(())
}

/// Write the scaffold for `preset` into `root`.
///
/// # Errors
///
/// [`InitError::Exists`] when `crunk.toml` exists without `force`; other variants for an
/// unknown preset, an invalid generated spec or an unwritable path.
pub fn scaffold(root: &Path, preset: &str, force: bool) -> Result<InitData, InitError> {
    let config = root.join("crunk.toml");
    if config.exists() && !force {
        return Err(InitError::Exists);
    }
    let base =
        crunk_spec::presets::preset(preset).ok_or_else(|| InitError::Preset(preset.to_owned()))?;
    let found = detect::detect(root);
    let (extra, detected) = detect::sections(&found);
    let text = format!("{}{extra}", base.trim_end_matches('\n').to_owned() + "\n");
    let spec =
        crunk_spec::parse_spec(&text, &config, root).map_err(|e| InitError::Spec(e.to_string()))?;

    let css_root = spec.css_root();
    let mut written = Vec::new();
    write_file(&config, &text)?;
    written.push(config);
    for bucket in &spec.org.buckets {
        let keep = css_root.join(bucket).join(".gitkeep");
        write_file(&keep, "")?;
        written.push(keep);
    }
    let reset = css_root.join("base").join("reset.css");
    if force || !reset.exists() {
        write_file(&reset, RESET_CSS)?;
        written.push(reset);
    }
    let report =
        crunk_tokens::export::write_all(&spec).map_err(|e| InitError::Tokens(e.to_string()))?;
    written.extend(report.written.into_iter().map(|w| w.path));

    let mut written: Vec<String> = written
        .iter()
        .map(|p| gob_path::forward_slashes(p.strip_prefix(root).unwrap_or(p)))
        .collect();
    written.sort();
    written.dedup();
    Ok(InitData {
        preset: preset.to_owned(),
        detected,
        written,
    })
}
