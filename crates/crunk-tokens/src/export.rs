//! The token exporters: render the CSS, flat-JSON and Tailwind targets from a [`TokenSet`] and
//! compare a rendered target with the file on disk.
//!
//! Every renderer is a pure function of the spec and token set, so the same bytes feed
//! `crunk tokens` (write, preview, `--check`) and the `TOKENS001` drift rule.

// frob:ticket 01M43ARZH9F9MCPJCKXM635E0X

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use crunk_spec::DesignSpec;
use crunk_spec::normalize_join;
use serde::Serialize;

use crate::model::{ThemeSection, TokenKind, TokenSet, TokenValue};

/// The banner line every generated `tokens.css` carries.
pub const BANNER: &str = "/* GENERATED by crunk tokens -- edit crunk.toml instead. */";

/// One export target.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum Target {
    /// `tokens.css`, compared byte for byte.
    Css,
    /// The flat JSON export, compared after parsing.
    Json,
    /// The Tailwind theme mapping JSON, compared after parsing.
    Tailwind,
}

impl Target {
    /// Every target in write order.
    pub const ALL: [Target; 3] = [Target::Css, Target::Json, Target::Tailwind];

    /// The target's CLI name (`css`, `json`, `tailwind`).
    pub fn name(self) -> &'static str {
        match self {
            Self::Css => "css",
            Self::Json => "json",
            Self::Tailwind => "tailwind",
        }
    }

    /// Parse a CLI name; `None` for anything else.
    pub fn parse(name: &str) -> Option<Self> {
        Self::ALL.into_iter().find(|t| t.name() == name)
    }
}

/// A rendered target and the file it belongs in.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct GeneratedFile {
    /// Which target this is.
    pub target: Target,
    /// Absolute destination path.
    pub path: PathBuf,
    /// The exact bytes the exporter produces, as text.
    pub content: String,
}

/// How an on-disk file relates to its rendered target.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum Drift {
    /// The file matches (bytes for CSS, parsed value for JSON).
    Clean,
    /// The file exists and differs.
    Drifted,
    /// The file does not exist.
    Missing,
}

/// Render `tokens.css`: the configured header (if any), the banner, then one `:root` block.
pub fn render_css(spec: &DesignSpec, tokens: &TokenSet) -> String {
    let mut out = String::new();
    if !spec.tokens.header.is_empty() {
        out.push_str(&spec.tokens.header);
        out.push('\n');
    }
    out.push_str(BANNER);
    out.push_str("\n:root {\n");
    for (name, value) in tokens.css_entries() {
        out.push_str("  ");
        out.push_str(name);
        out.push_str(": ");
        out.push_str(&value);
        out.push_str(";\n");
    }
    out.push_str("}\n");
    tracing::debug!(bytes = out.len(), "rendered css");
    out
}

/// Render the flat JSON export: bare token names to CSS values, sorted, two-space indent.
pub fn render_json(tokens: &TokenSet) -> String {
    let map: BTreeMap<&str, String> = tokens
        .css_entries()
        .into_iter()
        .map(|(name, value)| (crate::naming::bare_name(name), value))
        .collect();
    let out = dump(&map);
    tracing::debug!(bytes = out.len(), "rendered json");
    out
}

/// The Tailwind document: one map per theme section plus `fontFamily`, keys sorted.
#[derive(Serialize)]
struct TailwindDoc {
    #[serde(rename = "borderRadius")]
    border_radius: BTreeMap<String, String>,
    colors: BTreeMap<String, String>,
    #[serde(rename = "fontFamily")]
    font_family: BTreeMap<String, Vec<String>>,
    #[serde(rename = "fontSize")]
    font_size: BTreeMap<String, String>,
    height: BTreeMap<String, String>,
    #[serde(rename = "maxHeight")]
    max_height: BTreeMap<String, String>,
    #[serde(rename = "maxWidth")]
    max_width: BTreeMap<String, String>,
    #[serde(rename = "minHeight")]
    min_height: BTreeMap<String, String>,
    #[serde(rename = "minWidth")]
    min_width: BTreeMap<String, String>,
    spacing: BTreeMap<String, String>,
    width: BTreeMap<String, String>,
    #[serde(rename = "zIndex")]
    z_index: BTreeMap<String, String>,
}

/// Render the Tailwind theme-mapping JSON for `spec`'s `namespace_keys` and `alpha_channels`.
pub fn render_tailwind(spec: &DesignSpec, tokens: &TokenSet) -> String {
    let (ns, alpha) = (spec.tailwind.namespace_keys, spec.tailwind.alpha_channels);
    let section = |s: ThemeSection| -> BTreeMap<String, String> {
        tokens.theme_section(s, ns, alpha).into_iter().collect()
    };
    let font_family = tokens
        .of_kind(TokenKind::FontFamily)
        .filter_map(|t| match &t.value {
            TokenValue::FontFamily(families) => Some((t.key.clone(), families.clone())),
            _ => None,
        })
        .collect();
    let doc = TailwindDoc {
        border_radius: section(ThemeSection::BorderRadius),
        colors: section(ThemeSection::Colors),
        font_family,
        font_size: section(ThemeSection::FontSize),
        height: section(ThemeSection::Height),
        max_height: section(ThemeSection::MaxHeight),
        max_width: section(ThemeSection::MaxWidth),
        min_height: section(ThemeSection::MinHeight),
        min_width: section(ThemeSection::MinWidth),
        spacing: section(ThemeSection::Spacing),
        width: section(ThemeSection::Width),
        z_index: section(ThemeSection::ZIndex),
    };
    let out = dump(&doc);
    tracing::debug!(bytes = out.len(), "rendered tailwind");
    out
}

/// Render one `target` regardless of whether the spec configures a file for it.
pub fn render(spec: &DesignSpec, tokens: &TokenSet, target: Target) -> String {
    match target {
        Target::Css => render_css(spec, tokens),
        Target::Json => render_json(tokens),
        Target::Tailwind => render_tailwind(spec, tokens),
    }
}

/// The destination of `target`, or `None` when the spec configures no file for it.
pub fn target_path(spec: &DesignSpec, target: Target) -> Option<PathBuf> {
    match target {
        Target::Css => Some(spec.tokens_path()),
        Target::Json => spec.json_tokens_path(),
        Target::Tailwind => spec.tailwind_tokens_path(),
    }
}

/// Every file the spec configures, rendered, in write order (CSS, JSON, Tailwind).
///
/// This is what `TOKENS001` takes as expected bytes.
pub fn generated_files(spec: &DesignSpec, tokens: &TokenSet) -> Vec<GeneratedFile> {
    Target::ALL
        .into_iter()
        .filter_map(|target| {
            Some(GeneratedFile {
                target,
                path: target_path(spec, target)?,
                content: render(spec, tokens, target),
            })
        })
        .collect()
}

/// Compare `file` with the `on_disk` bytes (`None` when absent): CSS byte for byte, JSON after
/// parsing so a formatter rewrap is clean and a value edit is not.
pub fn compare(file: &GeneratedFile, on_disk: Option<&[u8]>) -> Drift {
    let Some(disk) = on_disk else {
        return Drift::Missing;
    };
    let clean = match file.target {
        Target::Css => disk == file.content.as_bytes(),
        Target::Json | Target::Tailwind => {
            let want: Result<serde_json::Value, _> = serde_json::from_str(&file.content);
            let have: Result<serde_json::Value, _> = serde_json::from_slice(disk);
            matches!((want, have), (Ok(w), Ok(h)) if w == h)
        }
    };
    if clean { Drift::Clean } else { Drift::Drifted }
}

/// Advisory warnings for a write or check: default-theme collisions (when a Tailwind file is
/// configured) and a possibly orphaned `tokens.css` at the project root.
pub fn warnings(spec: &DesignSpec, tokens: &TokenSet) -> Vec<String> {
    let mut out = Vec::new();
    if spec.tailwind_tokens_path().is_some() {
        for c in tokens.default_theme_collisions(spec.tailwind.namespace_keys) {
            let section = c.section.name();
            let effect = if c.section == ThemeSection::Spacing {
                "p-4 etc.".to_owned()
            } else {
                format!("the default {section} utilities")
            };
            out.push(format!(
                "theme.extend.{section} key '{}' collides with Tailwind's default {section} key; \
                 it will redefine {effect} -- set namespace_keys = true or rename the scale step",
                c.key
            ));
        }
    }
    let stale = normalize_join(&spec.root, &spec.project.tokens_file);
    if stale != spec.tokens_path() && stale.is_file() {
        out.push(orphan_warning(&stale, &spec.css_root()));
    }
    tracing::debug!(count = out.len(), "export warnings");
    out
}

fn orphan_warning(stale: &Path, css_root: &Path) -> String {
    format!(
        "possibly orphaned generated copy at {}; this key resolves against {}",
        stale.display(),
        css_root.display()
    )
}

/// `json.dumps(value, sort_keys=True, indent=2)` plus a newline, with non-ASCII escaped.
fn dump<T: Serialize>(value: &T) -> String {
    let text = serde_json::to_string_pretty(value)
        .unwrap_or_else(|e| unreachable!("string maps always serialize: {e}"));
    let mut out = String::with_capacity(text.len() + 1);
    for ch in text.chars() {
        if ch.is_ascii() {
            out.push(ch);
        } else {
            let mut units = [0u16; 2];
            for unit in ch.encode_utf16(&mut units) {
                let _ = write!(out, "\\u{unit:04x}");
            }
        }
    }
    out.push('\n');
    out
}
