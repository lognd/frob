//! The C# token class exporter: engine-free, plain floats, so an assembly with no engine
//! reference can use it (hullbreach D3 rule).
//!
//! `CrunkTokens` holds the default values; `CrunkTokens<Mode>` holds every token resolved in that
//! mode. Colors are `CrunkColor` (four floats), dimensions and durations are `float`, z-indexes
//! are `int`, font stacks are `string[]`, easings are `float[4]`. Aliases are resolved; channel
//! companions and composites are skipped.

// frob:ticket 01M4CXQZEYWB5WNCMFXYCNEE4J

use std::path::PathBuf;

use crunk_spec::DesignSpec;

use super::{Comparison, Exporter, Target};
use crate::model::{TokenSet, TokenValue};
use crate::naming::bare_name;

/// The banner line every generated C# file carries.
pub const CSHARP_BANNER: &str = "// GENERATED by crunk tokens -- edit crunk.toml instead.";

/// `PascalCase` an identifier from a token or mode name (`color-ink` to `ColorInk`).
pub(super) fn pascal(name: &str) -> String {
    let mut out = String::new();
    for part in name.split(|c: char| !c.is_ascii_alphanumeric()) {
        let mut chars = part.chars();
        if let Some(first) = chars.next() {
            out.push(first.to_ascii_uppercase());
            out.push_str(chars.as_str());
        }
    }
    if out.starts_with(|c: char| c.is_ascii_digit()) {
        out.insert(0, '_');
    }
    out
}

#[allow(
    clippy::float_cmp,
    reason = "whole exactly when equal to its truncation"
)]
fn float(value: f64) -> String {
    // Single precision is what the C# side stores; print the shortest f32 round-trip.
    #[allow(
        clippy::cast_possible_truncation,
        reason = "C# floats are single precision"
    )]
    let v = value as f32;
    if v == v.trunc() && v.abs() < 1e7 {
        format!("{v:.0}f")
    } else {
        format!("{v}f")
    }
}

fn string_lit(text: &str) -> String {
    format!("\"{}\"", text.replace('\\', "\\\\").replace('"', "\\\""))
}

/// The `(type, initializer, is_const)` of a value, or `None` when C# has no form for it.
fn csharp_value(value: &TokenValue) -> Option<(&'static str, String, bool)> {
    match value {
        TokenValue::Color(c) => Some((
            "CrunkColor",
            format!(
                "new CrunkColor({}, {}, {}, {})",
                float(c.r),
                float(c.g),
                float(c.b),
                float(c.a)
            ),
            false,
        )),
        TokenValue::Dimension { value, .. } | TokenValue::Duration(value) => {
            Some(("float", float(*value), true))
        }
        TokenValue::Number(n) => Some(("int", n.to_string(), true)),
        TokenValue::Float(f) => Some(("float", float(*f), true)),
        TokenValue::Text(t) => Some(("string", string_lit(t), true)),
        TokenValue::FontFamily(names) => {
            let items: Vec<String> = names.iter().map(|n| string_lit(n)).collect();
            Some((
                "string[]",
                format!("new[] {{ {} }}", items.join(", ")),
                false,
            ))
        }
        TokenValue::CubicBezier(p) => {
            let items: Vec<String> = p.iter().map(|v| float(*v)).collect();
            Some((
                "float[]",
                format!("new[] {{ {} }}", items.join(", ")),
                false,
            ))
        }
        TokenValue::Channels { .. } | TokenValue::Alias(_) | TokenValue::Composite(_) => None,
    }
}

fn class_lines(tokens: &TokenSet, class: &str, mode: Option<&str>, out: &mut Vec<String>) {
    out.push(format!("    public static class {class}"));
    out.push("    {".to_owned());
    for token in tokens.iter() {
        let Some((ty, init, is_const)) = tokens.resolve(&token.name, mode).and_then(csharp_value)
        else {
            continue;
        };
        let ident = pascal(bare_name(&token.name));
        if is_const {
            out.push(format!("        public const {ty} {ident} = {init};"));
        } else {
            out.push(format!(
                "        public static readonly {ty} {ident} = {init};"
            ));
        }
    }
    out.push("    }".to_owned());
}

/// Renders the C# token class file.
#[derive(Debug, Clone, Copy, Default)]
pub struct CsharpExporter;

impl Exporter for CsharpExporter {
    fn target(&self) -> Target {
        Target::Csharp
    }

    /// The banner, a `CrunkColor` struct, `CrunkTokens`, then `CrunkTokens<Mode>` per mode.
    fn render(&self, _spec: &DesignSpec, tokens: &TokenSet) -> String {
        let mut lines: Vec<String> = vec![
            CSHARP_BANNER.to_owned(),
            "namespace Crunk".to_owned(),
            "{".to_owned(),
            "    public readonly struct CrunkColor".to_owned(),
            "    {".to_owned(),
            "        public readonly float R, G, B, A;".to_owned(),
            "        public CrunkColor(float r, float g, float b, float a)".to_owned(),
            "        {".to_owned(),
            "            R = r; G = g; B = b; A = a;".to_owned(),
            "        }".to_owned(),
            "    }".to_owned(),
            String::new(),
        ];
        class_lines(tokens, "CrunkTokens", None, &mut lines);
        for mode in tokens.mode_names() {
            lines.push(String::new());
            class_lines(
                tokens,
                &format!("CrunkTokens{}", pascal(mode)),
                Some(mode),
                &mut lines,
            );
        }
        lines.push("}".to_owned());
        let mut text = lines.join("\n");
        text.push('\n');
        text
    }

    fn path(&self, _spec: &DesignSpec) -> Option<PathBuf> {
        None
    }

    fn comparison(&self) -> Comparison {
        Comparison::Bytes
    }
}
