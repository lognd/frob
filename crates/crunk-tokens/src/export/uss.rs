//! The Unity USS exporter: custom properties on `:root`, then one override block per mode.
//!
//! USS has no `var()` inside functions and no arithmetic on variables, so only values USS can
//! hold as a single custom property are written: colors, dimensions, numbers, durations and
//! aliases. Font stacks, easings, the `-rgb` channel companions and composites are skipped.

// frob:ticket 01M4CXQZEYWB5WNCMFXYCNEE4J

use std::path::PathBuf;

use crunk_spec::DesignSpec;

use super::{Comparison, Exporter, Target};
use crate::model::{TokenSet, TokenValue};

/// The banner line every generated USS sheet carries.
pub const USS_BANNER: &str = "/* GENERATED by crunk tokens -- edit crunk.toml instead. */";

/// The class a mode's override block selects (`dark` to `.crunk-mode-dark`).
pub(super) fn mode_class(mode: &str) -> String {
    let slug: String = mode
        .chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() {
                c.to_ascii_lowercase()
            } else {
                '-'
            }
        })
        .collect();
    format!(".crunk-mode-{slug}")
}

fn uss_supported(value: &TokenValue) -> bool {
    matches!(
        value,
        TokenValue::Color(_)
            | TokenValue::Dimension { .. }
            | TokenValue::Number(_)
            | TokenValue::Duration(_)
            | TokenValue::Alias(_)
    )
}

/// Renders the USS token sheet.
#[derive(Debug, Clone, Copy, Default)]
pub struct UssExporter;

impl Exporter for UssExporter {
    fn target(&self) -> Target {
        Target::Uss
    }

    /// The banner, `:root { --name: value; }`, then `.crunk-mode-<mode> { ... }` per mode holding
    /// only the tokens that mode overrides.
    fn render(&self, _spec: &DesignSpec, tokens: &TokenSet) -> String {
        let mut lines = vec![USS_BANNER.to_owned(), ":root {".to_owned()];
        for token in tokens.iter().filter(|t| uss_supported(&t.value)) {
            if let Some(css) = token.value.css() {
                lines.push(format!("  {}: {css};", token.name));
            }
        }
        lines.push("}".to_owned());
        for mode in tokens.mode_names() {
            let rows: Vec<String> = tokens
                .iter()
                .filter_map(|t| {
                    let value = t.modes.get(mode).filter(|v| uss_supported(v))?;
                    Some(format!("  {}: {};", t.name, value.css()?))
                })
                .collect();
            if rows.is_empty() {
                tracing::debug!(mode, "mode has no USS-expressible overrides");
                continue;
            }
            lines.push(format!("{} {{", mode_class(mode)));
            lines.extend(rows);
            lines.push("}".to_owned());
        }
        let mut text = lines.join("\n");
        text.push('\n');
        text
    }

    fn path(&self, _spec: &DesignSpec) -> Option<PathBuf> {
        None
    }

    fn comparison(&self) -> Comparison {
        Comparison::Bytes
    }
}
