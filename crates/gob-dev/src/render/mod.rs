/// The generator version stamped into every marker.
pub const GENERATOR_VERSION: &str = env!("CARGO_PKG_VERSION");

/// What a generator of `kind` reads, named in the marker's `Source:` field.
pub fn source_of(kind: &str) -> &'static str {
    match kind {
        "rules" | "rules-index" => "rule declarations",
        "directives" => "directive declarations",
        "config" => "config table declarations",
        "cli" => "command registry",
        "inline" => "inline test comments in parser source",
        "std-rules" => "std GRL sources (packs/std/rules)",
        _ => "schema declarations",
    }
}

// frob:ticket 01M4MAQ5JFANPHZ0SJ690R68TZ
/// The one-line marker text for `kind`: `GENERATED by frob v<version>: DO NOT EDIT. Regenerate: <command>. Source: <source>`.
pub fn marker_text(kind: &str) -> String {
    format!(
        "GENERATED by frob v{GENERATOR_VERSION}: DO NOT EDIT. Regenerate: cargo dev gen {kind}. Source: {}",
        source_of(kind)
    )
}

/// Header comment of every generated markdown file.
pub fn md_header(kind: &str) -> String {
    format!("<!-- {} -->\n", marker_text(kind))
}

// frob:ticket 01M4MAQ5JFANPHZ0SJ690R68TZ
/// Insert the visible `> Generated: ...` line under the first `# ` title of generated markdown `text`; other text is returned unchanged.
pub fn with_visible_line(text: String) -> String {
    if !text.starts_with("<!-- GENERATED by ") {
        return text;
    }
    let kind = crate::files::marker_command(&text)
        .unwrap_or("all")
        .to_owned();
    let mut out = String::with_capacity(text.len() + 120);
    let mut done = false;
    for line in text.split_inclusive('\n') {
        out.push_str(line);
        if !done && line.starts_with("# ") {
            done = true;
            out.push_str(&format!(
                "\n> Generated: do not edit this page. Regenerate with `cargo dev gen {kind}`.\n"
            ));
        }
    }
    out
}

/// Escape a markdown table cell: pipes escaped, line breaks flattened.
pub fn cell(text: &str) -> String {
    text.trim().replace('|', "\\|").replace(['\r', '\n'], " ")
}

/// Pretty JSON with a `$comment` header field and a trailing newline.
pub fn json_file(kind: &str, mut value: serde_json::Value) -> String {
    if let Some(obj) = value.as_object_mut() {
        obj.insert("$comment".to_owned(), marker_text(kind).into());
    }
    let mut text = serde_json::to_string_pretty(&value)
        .unwrap_or_else(|_| unreachable!("a serde_json Value always serializes"));
    text.push('\n');
    text
}
