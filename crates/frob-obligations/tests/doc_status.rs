//! DOC003: every document under `docs/` carries one status header from the fixed vocabulary.

// frob:ticket 01M4H0RKJHHWWT0XC17W5JD1VG

mod common;

use frob_obligations::InvariantsConfig;
use gob_rules::Finding;

/// A well-formed header block.
const GOOD: &str = "# Good\n\nStatus: current\nOwner: frob\n\nBody.\n";

/// Evaluate a tree holding `files`; return the DOC003 findings.
fn doc003(files: &[(&str, &str)]) -> Vec<Finding> {
    let dir = tempfile::tempdir().expect("tempdir");
    common::write_tree(dir.path(), &[("frob.toml", "")]);
    common::write_tree(dir.path(), files);
    let config = InvariantsConfig::load(dir.path()).expect("config");
    let eval = common::evaluate_tree(dir.path(), None, &config, None);
    eval.findings
        .into_iter()
        .filter(|f| f.rule.as_str() == "DOC003")
        .collect()
}

// frob:tests doc003
#[test]
fn document_without_a_status_header_is_named() {
    let found = doc003(&[("docs/a.md", "# A\n\nJust prose.\n")]);
    assert_eq!(found.len(), 1, "{found:?}");
    assert!(found[0].message.contains("Status:"), "{}", found[0].message);
}

// frob:tests doc003
#[test]
fn status_outside_the_vocabulary_is_named() {
    let found = doc003(&[("docs/a.md", "# A\n\nStatus: wip\nOwner: frob\n")]);
    assert_eq!(found.len(), 1, "{found:?}");
    assert!(found[0].message.contains("wip"), "{}", found[0].message);
}

// frob:tests doc003
#[test]
fn superseded_by_naming_a_missing_document_is_named() {
    let found = doc003(&[(
        "docs/a.md",
        "# A\n\nStatus: superseded-by nowhere.md\nOwner: frob\n",
    )]);
    assert_eq!(found.len(), 1, "{found:?}");
    assert!(
        found[0].message.contains("nowhere.md"),
        "{}",
        found[0].message
    );
}

// frob:tests doc003
#[test]
fn valid_headers_and_existing_targets_are_clean() {
    let found = doc003(&[
        ("docs/a.md", GOOD),
        (
            "docs/b.md",
            "# B\n\nStatus: superseded-by a.md\nOwner: frob\n",
        ),
        ("docs/c.md", "# C\n\nStatus: historical\nOwner: frob\n"),
        ("docs/d.md", "# D\n\nStatus: draft\nOwner: frob\n"),
        (
            "docs/e.md",
            "<!-- GENERATED by x: DO NOT EDIT. -->\n\n# E\n",
        ),
        ("src/readme.md", "# not under docs\n"),
    ]);
    assert!(found.is_empty(), "{found:?}");
}
