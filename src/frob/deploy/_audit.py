class CheckpointResult(BaseModel):
    """One CHECK's recorded outcome (module docstring: C0/C1/C1'/C2) --
    the state label and the status assertion result at that checkpoint."""

    model_config = ConfigDict(frozen=True)

    label: str
    status_assertion: str
    status_assertion_passed: bool


# frob:doc docs/commands/deploy.md#attestation
class AuditAttestation(BaseModel):
    """The full `frob deploy audit --vm` attestation record (module
    docstring) -- snapshot ids, per-checkpoint status assertions, and the
    three diff-based proof results, everything `--evidence-cmd` (T-0215)
    needs to record this run as ticket evidence without re-deriving
    anything from raw captures."""

    model_config = ConfigDict(frozen=True)

    vm_name: str
    base_snapshot: str
    started_at: datetime
    finished_at: datetime
    checkpoints: tuple[CheckpointResult, ...]
    idempotence_holds: bool
    artifact_freeness_holds: bool
    install_exactness_holds: bool
    install_exactness_extra: tuple[str, ...]
    install_exactness_missing: tuple[str, ...]

    # frob:doc docs/commands/deploy.md#attestation
    @property
    def passed(self) -> bool:
        """`True` iff every proof holds AND every checkpoint's status
        assertion passed -- the single field `frob deploy audit`'s exit
        code is derived from."""
        return (
            self.idempotence_holds
            and self.artifact_freeness_holds
            and self.install_exactness_holds
            and all(c.status_assertion_passed for c in self.checkpoints)
        )

    # frob:doc docs/commands/deploy.md#attestation
    def to_json(self) -> str:
        """Deterministic (sorted-key) JSON serialization -- the exact text
        `frob deploy audit` writes to its output file and hands to
        `--evidence-cmd`."""
        return json.dumps(self.model_dump(mode="json"), sort_keys=True, indent=2)


# frob:doc docs/commands/deploy.md#attestation
def build_attestation(
    *,
    vm_name: str,
    base_snapshot: str,
    started_at: datetime,
    checkpoints: tuple[CheckpointResult, ...],
    s0: StateCapture,
    s1: StateCapture,
    s1_prime: StateCapture,
    s2: StateCapture,
    expected_surface: frozenset[MutationTarget],
    finished_at: datetime | None = None,
) -> AuditAttestation:
    """Run all three diff-based proofs over the four captured states and
    assemble the `AuditAttestation` -- the one call site `_vm_runner.py`'s
    orchestration and every fixture-based unit test share, so the proof
    wiring is identical whether the captures came from a real VM or a
    test fixture dict."""
    idempotent = idempotence_holds(s1, s1_prime)
    artifact_free = artifact_freeness_holds(s0, s2)
    exact, extra, missing = install_exactness_holds(s0, s1, expected_surface)
    return AuditAttestation(
        vm_name=vm_name,
        base_snapshot=base_snapshot,
        started_at=started_at,
        finished_at=finished_at or datetime.now(UTC),
        checkpoints=checkpoints,
        idempotence_holds=idempotent,
        artifact_freeness_holds=artifact_free,
        install_exactness_holds=exact,
        install_exactness_extra=tuple(sorted(t.target for t in extra)),
        install_exactness_missing=tuple(sorted(t.target for t in missing)),
    )
